'use strict';
const assert=require('node:assert/strict');
const {createEngine,VERSION}=require('../engine.js');
let assertions=0;
function check(actual,expected,msg){assertions++;assert.equal(actual,expected,msg);}
const e=createEngine(),send=a=>e.dispatch(a);
const normal=()=>e.evaluate().indications;
check(VERSION,'3.0.0','V3 version');
check(e.getState().selectors.ENG1,'NORMAL','ENG 1 normal');
check(e.getState().selectors.ENG2,'NORMAL','ENG 2 normal');
check(normal().FAULT,false,'no initial fault');
send({type:'SELECT_LOOP',unit:'ENG1',value:'A'});
check(e.getState().selectors.ENG1,'A','selected engine one');
check(e.getState().selectors.ENG2,'NORMAL','engine two independent');
send({type:'SELECT_LOOP',unit:'ENG1',value:'NORMAL'});
send({type:'SET_SENSOR',unit:'ENG1',loop:'A',kind:'fire',active:true});
check(normal().ENG1_FIRE,false,'healthy dual-loop requires concurrence');
send({type:'SET_SENSOR',unit:'ENG1',loop:'B',kind:'fire',active:true});
check(normal().ENG1_FIRE,true,'both loops signal fire');
check(normal().ENG1_OVERHEAT,true,'fire implies overheat/caution');
check(normal().MASTER_CAUTION,true,'engine fire has related overheat indications');
check(e.evaluate().handleUnlock.ENG1,true,'fire unlock');
send({type:'RESET'});
send({type:'SET_LOOP',unit:'ENG1',loop:'A',healthy:false});
check(normal().FAULT,false,'one failed normal loop has no alert');
send({type:'SET_SENSOR',unit:'ENG1',loop:'B',kind:'fire',active:true});
check(normal().ENG1_FIRE,true,'remaining single healthy loop detects');
send({type:'SET_LOOP',unit:'ENG1',loop:'B',healthy:false});
check(normal().ENG1_FIRE,false,'both failed loops cannot detect');
check(normal().FAULT,true,'both failed loops FAULT');
check(normal().OVHT_DET,true,'double failure triggers OVHT DET');
check(normal().MASTER_CAUTION,true,'double failure triggers caution');
send({type:'SELECT_LOOP',unit:'ENG1',value:'A'});
check(normal().FAULT,true,'selected failed loop FAULT');
check(normal().MASTER_CAUTION,false,'single-loop selector fault no caution');
send({type:'RESET'});
send({type:'SET_OVERHEAT',unit:'ENG2',active:true});
check(normal().ENG2_OVERHEAT,true,'overheat indication');
check(normal().ENG2_FIRE,false,'overheat is not fire');
check(e.evaluate().handleUnlock.ENG2,true,'overheat unlocks switch');
send({type:'RESET'});
send({type:'SET_FIRE',unit:'APU',active:true});
check(normal().APU_FIRE,true,'APU fire');
check(normal().APU_GROUND_HORN,true,'APU horn on ground');
check(e.evaluate().outputs.APU.autoShutdown,true,'APU automatic shutdown');
send({type:'SET_POWER',bus:'onGround',active:false});
check(normal().APU_GROUND_HORN,false,'no horn in flight');
send({type:'RESET'});
send({type:'SET_WHEEL_FIRE',active:true});
check(normal().WHEEL_WELL,true,'wheel warning');
send({type:'SET_POWER',bus:'acTransfer1',active:false});
check(normal().WHEEL_WELL,false,'wheel detector requires AC transfer 1');
send({type:'RESET'});
send({type:'TEST',value:'FAULT_INOP'});
check(normal().FAULT,true,'fault test');
check(normal().APU_DET_INOP,true,'APU inop test');
check(normal().MASTER_CAUTION,true,'fault test triggers caution');
send({type:'TEST',value:null});
check(normal().FAULT,false,'test spring returns off');
send({type:'TEST',value:'OVHT_FIRE'});
check(normal().ENG1_FIRE,true,'fire test ENG1');
check(normal().ENG2_FIRE,true,'fire test ENG2');
check(normal().APU_FIRE,true,'fire test APU');
check(normal().WHEEL_WELL,true,'wheel test AC present');
check(normal().ENG1_OVERHEAT,true,'test overheat');
send({type:'SET_LOOP',unit:'ENG1',loop:'A',healthy:false});
check(normal().FAULT,true,'Kidde OVHT test reveals detector failure');
send({type:'RESET'});
send({type:'TEST',value:'EXT_1'});
check(normal().EXT_L,true,'EXT 1 L continuity');
check(normal().EXT_R,true,'EXT 1 R continuity');
check(normal().EXT_APU,true,'EXT 1 APU continuity');
check(normal().APU_BOTTLE_DISCHARGED,false,'test does not discharge bottle');
send({type:'SET_CIRCUIT',bottle:'APU',channel:1,healthy:false});
check(normal().EXT_APU,false,'failed squib channel extinguishes test lens');
send({type:'TEST',value:'EXT_2'});
check(normal().EXT_APU,true,'other APU squib channel independent');
send({type:'TEST',value:null});
check(normal().EXT_L,false,'spring returned test');
send({type:'RESET'});
check(send({type:'PULL',unit:'ENG1'}).result.reason,'HANDLE_LOCKED','fire handle locked');
check(send({type:'ROTATE',unit:'ENG1',angle:-45}).result.reason,'PULL_FIRST','pull before rotation');
send({type:'OVERRIDE',unit:'ENG1',enabled:true});
check(send({type:'PULL',unit:'ENG1'}).result.accepted,true,'manual override');
check(e.evaluate().outputs.ENG1.fuelShutoff,true,'engine fuel valve');
check(e.evaluate().outputs.ENG1.hydraulicShutoff,true,'engine hydraulic valve');
check(e.evaluate().outputs.ENG1.bleedShutoff,true,'engine bleed');
check(e.evaluate().outputs.ENG1.generatorTrip,true,'generator trip');
check(e.evaluate().outputs.ENG1.reverserInhibit,true,'reverser inhibit');
check(send({type:'ROTATE',unit:'ENG1',angle:-45}).result.accepted,true,'discharge command accepted');
check(normal().L_BOTTLE_DISCHARGED,false,'delayed light, no immediate discharge');
send({type:'TICK',seconds:2.6});
check(normal().L_BOTTLE_DISCHARGED,true,'bottle pressure low after discharge delay');
check(send({type:'PULL',unit:'ENG1',pulled:false}).result.reason,'RETURN_ROTATION_TO_CENTER','cannot return rotated switch');
send({type:'ROTATE',unit:'ENG1',angle:0});
check(send({type:'PULL',unit:'ENG1',pulled:false}).result.accepted,true,'handle returns');
send({type:'RESET'});
send({type:'SET_FIRE',unit:'ENG1',active:true});
check(normal().FIRE_BELL,true,'new warning bell');
send({type:'BELL_CUTOUT'});
check(normal().FIRE_BELL,false,'bell cutout');
check(normal().MASTER_FIRE_WARN,false,'warn resets');
send({type:'SET_WHEEL_FIRE',active:true});
check(normal().FIRE_BELL,true,'new fire event sounds again');
send({type:'RESET'});
send({type:'SET_BOTTLE_LOW',bottle:'APU',active:true});
check(normal().APU_BOTTLE_DISCHARGED,true,'low pressure APU bottle lamp');
check(normal().L_BOTTLE_DISCHARGED,false,'independent bottle lamps');
send({type:'RESET'});
send({type:'OVERRIDE',unit:'APU',enabled:true});
send({type:'PULL',unit:'APU'});
send({type:'SET_POWER',bus:'hotBatteryBus',active:false});
check(send({type:'ROTATE',unit:'APU',angle:45}).result.reason,'NO_HOT_BATTERY_POWER','hot battery protects discharge');
assert.throws(()=>send({type:'SELECT_LOOP',unit:'ENG1',value:'INVALID'}),RangeError);
assert.throws(()=>send({type:'SET_CIRCUIT',bottle:'NO',healthy:true}),RangeError);
assert.throws(()=>send({type:'TICK',seconds:-1}),RangeError);
console.log('PASS Fire Protection v3 FCOM logic: '+assertions+' assertions + invalid input checks.');
