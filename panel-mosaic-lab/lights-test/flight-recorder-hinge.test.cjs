'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const here=path.resolve(__dirname,'..');
const read=p=>JSON.parse(fs.readFileSync(path.resolve(here,p),'utf8'));
const reg=read('interactive-overhead/lights.json'),controls=read('interactive-overhead/lights-controls.json');
const overlays=read('interactive-overhead/readability-faces.json');
const guard=controls.guards.find(c=>c.id==='flight-recorder-test');
const light=reg.lights.find(c=>c.id==='flight-recorder-off');
assert.ok(guard&&light);
assert.equal(guard.kind,'guarded');assert.equal(guard.presentation,'flight-recorder-left-hinge');
assert.equal(guard.hinge,'LEFT');
assert.deepEqual(guard.states,['test','normal']);
assert.deepEqual(guard.default,{value:'normal',guard:'closed'});
assert.deepEqual(guard.closePolicy,{force:'normal'});
assert.deepEqual(guard.sourceRect,[1365,438,113,34]);
assert.deepEqual(light.sourceRect,[1485,439,40,31]);
assert.deepEqual(light.controls,['flight-recorder-test']);
const [gx,gy,gw,gh]=guard.sourceRect,[lx,ly,lw,lh]=light.sourceRect;
assert.equal(lx-(gx+gw),7,'Only a genuine photo-safe 7px gap may separate the left guard and right OFF lens');
assert.ok(Math.abs(gy+gh/2-(ly+lh/2))<=1);
assert.equal(light.photoAnchor?.controlId,guard.id);
assert.equal(light.photoAnchor?.imageUnchanged,true);
assert.deepEqual(overlays.instances[light.id]?.sourceRect,light.sourceRect);
const controlCode=fs.readFileSync(path.resolve(here,'interactive-overhead/rotary-guards.js'),'utf8');
const css=fs.readFileSync(path.resolve(here,'interactive-overhead/rotary-guards.css'),'utf8');
const lightModel=fs.readFileSync(path.resolve(here,'interactive-overhead/lights-model.js'),'utf8');
assert.match(controlCode,/function recorderHinged\(c,placement\)/);
assert.match(controlCode,/engine\.guardAction\(c\.id,'set'/);
assert.match(controlCode,/c\.presentation==='flight-recorder-left-hinge'/);
assert.match(css,/\.recorder-hinge-unit\[data-guard="open"\]/);
assert.match(lightModel,/control\('flight-recorder-test'\)!=='test'/);
console.log('PASS: photo-safe OH06 7px lamp gap and <=1px vertical centre offset, interactive left hinge, NORMAL re-guard policy, genuine FDR TEST input and untouched source image.');
