'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=p=>JSON.parse(fs.readFileSync(path.resolve(__dirname,p),'utf8'));
const data=read('photo-pixel-registration-v2.json');
const baseline=read('photo-pixel-registration-2026-10-26.json');
const corrections=read('photo-position-corrections-v1.json');
const fitted=read('precision-faces-v1.json');
const overhead=read('../interactive-overhead/lights.json'),main=read('../cockpit/lights.json');
const current=new Map([...overhead.lights,...main.lights].map(l=>[l.id,l]));
const originals=new Map(baseline.records.map(l=>[l.id,l]));
const movement=new Map(corrections.records.map(l=>[l.id,l]));
const finalCorrections=read('photo-position-corrections-v2.json');
const latest=new Map(finalCorrections.records.map(c=>[c.id,c.newSourceRect]));
assert.equal(latest.size,1);
const fittedInstances=new Set(fitted.derivatives.map(l=>l.lamp));
assert.equal(data.sourceVersions.overhead,'LGT-0009');
assert.ok(['LGT-0009','LGT-0010'].includes(overhead.version));
assert.equal(data.sourceVersions.main,'LGT-0011');
assert.ok(['LGT-0011','LGT-0012'].includes(main.version));
assert.equal(data.summary.total,142);
assert.equal(data.records.length,142);
assert.equal(new Set(data.records.map(r=>r.id)).size,142);
assert.equal(data.summary.pixelAutoVerified,120);
assert.equal(data.summary.photoReviewedButPixelOpen,22);
assert.equal(movement.size,12);
assert.equal(fittedInstances.size,9);
assert.equal(fitted.derivatives.length,18);
assert.equal(data.summary.immutablePhotoEdits,0);
assert.equal(data.summary.lockedAtlasEdits,0);
let matches=0,photoOnly=0;
for(const row of data.records){
 const source=current.get(row.id),old=originals.get(row.id);
 assert.ok(source&&old,row.id);
 assert.deepEqual(row.currentSourceRect,old.sourceRect.map((v,i)=>v+(row.appliedDisplacement?.[i]||0)),row.id+' historical position');
 const c=movement.get(row.id);
 assert.deepEqual(row.appliedDisplacement,c?.delta||[0,0],row.id);
 assert.deepEqual(source.sourceRect,latest.get(row.id)||c?.sourceRect||old.sourceRect,row.id);
 assert.equal(row.visualFaceReflowed,fittedInstances.has(row.id),row.id);
 const passed=row.photoRimMethod==='AUTO_CENTRE_MATCH'||row.darkGlassComponentMethod==='PHOTO_COMPONENT_CENTRED';
 assert.equal(row.status,passed?'AUTO_PIXEL_CENTRE_MATCH_3PX':'PHOTO_ENLARGED_REVIEWED_PIXEL_PRECISION_OPEN',row.id);
 if(passed)matches++;else photoOnly++;
}
assert.equal(matches,120);
assert.equal(photoOnly,22);
console.log('PASS: 142 photographic lamp records; 120 strict 3-pixel checks, 22 enlarged native-image reviews; 12 source corrections and 9 derivative face reflows.');
