'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=p=>JSON.parse(fs.readFileSync(path.resolve(__dirname,p),'utf8'));
const v5=read('photo-pixel-registration-v5.json');
const v4=read('photo-pixel-registration-v4.json');
const special=read('photo-special-colour-v1.json');
const oh=read('../interactive-overhead/lights.json'),main=read('../cockpit/lights.json');
const overlayOH=read('../interactive-overhead/instance-faces.json');
const overlayMain=read('../cockpit/instance-faces.json');
const originals=new Map(v4.records.map(x=>[x.id,x]));
const current=new Map([...oh.lights,...main.lights].map(x=>[x.id,x]));
assert.equal(v5.summary.inspected,142);
assert.equal(v5.summary.verifiedPhotoPixelCentres,141);
assert.equal(v5.summary.notVerified,1);
assert.equal(v5.summary.originalImageEdits,0);
assert.equal(v5.summary.derivedVectorStatesTotal,119);
assert.equal(Object.keys(overlayOH.instances).length,35);
assert.equal(Object.keys(overlayMain.instances).length,2);
const captain=special.records.find(x=>x.id==='main-pull-up-captain');
const recorder=special.records.find(x=>x.id==='flight-recorder-off');
assert.equal(special.positionsChanged,0);
assert.equal(captain.fourIndependentEdges,true);
assert.ok(captain.centreDeviationNativePixels.every(x=>Math.abs(x)<=3));
for(const key of ['left','right','top','bottom']) assert.equal(captain.edgeEvidence[key].status,'MEASURED_RIM');
assert.equal(recorder.fourIndependentEdges,false);
assert.equal(recorder.edgeEvidence.left.status,'NO_SAFELY_ISOLATED_RIM');
assert.equal(v5.exception.id,'flight-recorder-off');
assert.equal(v5.records.length,142);
let good=0,bad=0;
for(const item of v5.records){
 const base=originals.get(item.id),mounted=current.get(item.id);
 assert.ok(base&&mounted,item.id);
 assert.deepEqual(item.currentSourceRect,base.currentSourceRect,item.id);
 assert.deepEqual(item.currentSourceRect,mounted.sourceRect,item.id);
 const expected=item.id==='main-pull-up-captain'?'PHOTO_PIXEL_CENTRE_CONFIRMED_3PX':base.finalPixelVerdict;
 assert.equal(item.finalGeometryVerdict,expected,item.id);
 if(expected==='PHOTO_PIXEL_CENTRE_CONFIRMED_3PX')good++;else bad++;
}
assert.equal(good,141);assert.equal(bad,1);
console.log('PASS: 141/142 pixel-calibrated source annunciators; PULL UP captain verified by RGB + grayscale; FLIGHT RECORDER OFF remains transparently uncertified.');
