'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const vm=require('node:vm');
const root=__dirname;
const spec=JSON.parse(fs.readFileSync(path.join(root,'spec.json'),'utf8'));
const geometry=JSON.parse(fs.readFileSync(path.join(root,'../upper-oh/geometry.json'),'utf8'));
assert.equal(spec.version,'UPD-0009-atlas-absolute');
assert.equal(spec.images.length,18,'18 distinct image sources');
assert.equal(new Set(spec.images.map(x=>x.filename)).size,18,'no duplicate image');
assert.deepEqual(spec.images[0].panelIds,['OH-01','OH-02','OH-03','OH-04','OH-05','OH-06']);
assert.deepEqual(spec.images[1].panelIds,['OH-07','OH-08']);
const ids=spec.images.flatMap(x=>x.panelIds);
assert.deepEqual([...new Set(ids)].sort(),Array.from({length:25},(_,i)=>'OH-'+String(i+1).padStart(2,'0')).sort());
assert.equal(ids.filter(x=>x==='OH-19').length,2,'OH19 combines separate voice recorder and press differential original plates');
assert.deepEqual(spec.columns.map(c=>c.items),[['OH07-08','OH09'],['OH10','OH11','OH12'],['OH13','OH14','OH18'],['OH15','OH16','OH17','OH19-VOICE','OH19-DIFF'],['OH20','OH21','OH22']]);
assert.equal(spec.columns.reduce((s,c)=>s+c.weight,0),2220);
assert.deepEqual(spec.bottomMissing,[]);
assert.deepEqual(spec.bottomItems,['OH23-25'],'shared lower overhead switching panel spans the whole width');
assert.deepEqual(spec.images.find(x=>x.id==='OH23-25').panelIds,['OH-23','OH-24','OH-25']);
const strip=spec.images.find(x=>x.id==='OH23-25');
assert.deepEqual([strip.display.cropTopPx,strip.display.cropBottomPx,strip.display.contentHeightPx],[212,216,297],'lower strip content crop trims white canvas but not locked file');
assert.deepEqual(spec.columns[4].missing,[],'OH22 pressurization has now been uploaded');
assert.equal(spec.columns[4].items.at(-1),'OH22','OH22 below Bleed Air at far right');
assert.equal(spec.columns[3].items[2],'OH17','hydraulic pump is the last instrument before OH19');
assert.equal(spec.columns[3].items[3],'OH19-VOICE','OH19 voice recorder directly under OH17');
assert.equal(spec.columns[3].items[4],'OH19-DIFF','OH19 press diff immediately after voice recorder in the same wide column');
assert.equal(spec.images.find(x=>x.id==='OH19-VOICE').atlasSizing.widthMode,'fill-column-natural-aspect');
assert.equal(geometry.parts.length,6);
assert.equal(spec.header.height,909);
assert.deepEqual(spec.correctedMappings.slice(0,3).map(x=>x.id),['OH13','OH14','OH18']);
for(const id of ['OH19-VOICE','OH19-DIFF','OH22','OH23-25'])assert.ok(spec.correctedMappings.some(x=>x.id===id),'atlas correction recorded: '+id);
assert.equal(spec.columns[2].items[2],'OH18','OH18 must be directly beneath OH14 in center strip');
assert.ok(spec.images.find(x=>x.id==='OH13').display.cropLeftPct>10,'OH13 light side gutters are cropped in presentation only');
assert.match(spec.images.find(x=>x.id==='OH18').title,/GROUND|GRD CALL/,'source identification comes from atlas photo');
assert.ok(fs.existsSync(path.resolve(root,spec.atlasReference.image)),'source overhead atlas must exist');
let count=0;
for(const item of spec.images){
 const full=path.resolve(root,item.url);
 assert.ok(full.startsWith(path.resolve(root,'../assets/locked/')),'all sources must be locked');
 const bytes=fs.readFileSync(full);
 assert.equal(bytes.length,item.bytes,'size: '+item.filename);
 const git=crypto.createHash('sha1').update(Buffer.concat([Buffer.from('blob '+bytes.length+String.fromCharCode(0)),bytes])).digest('hex');
 assert.equal(git,item.gitBlobSha,'Git blob identity: '+item.filename);
 if(item.sha256)assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),item.sha256,'SHA-256: '+item.filename);
 count+=bytes.length;
}
assert.equal(count,spec.confirmedBytes);
new vm.Script(fs.readFileSync(path.join(root,'stage.js'),'utf8'),{filename:'stage.js'});
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const name of ['stage.js','style.css','spec.json','upper','columns','gallery','viewport','zoomLabel','modeAtlas','atlasView'])assert.ok(html.includes(name),'page missing '+name);
console.log('PASS: 18 immutable sources / 25 atlas IDs. OH19 under OH17 and native aspect. OH22 cabin press, shared bottom OH23-25 with non-destructive 212px top crop.');
