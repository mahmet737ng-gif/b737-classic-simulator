'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('./cabin-rate-needle-model');
const atlas=JSON.parse(fs.readFileSync(path.join(__dirname,'../all-overhead/atlas-layout.json'),'utf8'));
const oh19=atlas.placements.find(piece=>piece.id===model.source.piece);
assert.ok(oh19);
assert.deepEqual(oh19.sourceDimensions,[model.source.width,model.source.height]);
assert.deepEqual(model.pivot,{x:520,y:950});
assert.equal(model.needle.initialOffset,0);
assert.equal(model.bearing(0),-90);
assert.equal(model.pivot.x-model.needle.tipRadius,381);
assert.equal(model.offset(200),145);assert.equal(model.offset(-200),-145);
assert.throws(()=>model.offset(NaN));
const at=model.placement(oh19);assert.ok(at.x>oh19.x&&at.x<oh19.x+oh19.w);assert.ok(at.y>oh19.y&&at.y<oh19.y+oh19.h);
const asset=fs.readFileSync(path.join(__dirname,model.needle.asset),'utf8');
assert.match(asset,/viewBox="0 0 512 512"/);assert.match(asset,/CABIN CLIMB/);assert.doesNotMatch(asset,/<image/);
const ui=fs.readFileSync(path.join(__dirname,'cabin-rate-needle-unified.js'),'utf8');
assert.ok(ui.includes('`.atlas-piece[data-key="${model.source.piece}"]`'));
assert.ok(ui.includes('model.bearing(currentOffset)'));
assert.ok(ui.includes('window.B737UnifiedCabinRateNeedle'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.ok(html.includes('cabin-rate-needle-model.js?v=CRN-0001'));
assert.ok(html.includes('cabin-rate-needle-unified.js?v=CRN-0001'));
console.log('PASS: lower CABIN CLIMB needle is independent and points to the left zero tick by default.');
