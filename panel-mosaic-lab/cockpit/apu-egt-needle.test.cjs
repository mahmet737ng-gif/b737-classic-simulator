'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('./apu-egt-needle-model');
const atlas=JSON.parse(fs.readFileSync(path.join(__dirname,'../all-overhead/atlas-layout.json'),'utf8'));
const oh12=atlas.placements.find(p=>p.id==='OH12');
assert.ok(oh12);
assert.deepEqual(oh12.sourceDimensions,[model.source.width,model.source.height]);
assert.equal(model.needle.id,'apuEgt');
const placement=model.placement(oh12);
assert.ok(placement.x>oh12.x&&placement.x<oh12.x+oh12.w);
assert.ok(placement.y>oh12.y&&placement.y<oh12.y+oh12.h);
assert.ok(placement.size>130&&placement.size<150);
assert.equal(model.angle(127),127);
assert.equal(model.angle(900),145);
assert.equal(model.angle(-900),-250);
assert.throws(()=>model.angle(NaN));
const sprite=fs.readFileSync(path.join(__dirname,'apu-egt-needle.svg'),'utf8');
assert.match(sprite,/viewBox="0 0 512 512"/);
assert.match(sprite,/hollow loop and twin fine tips/);
assert.doesNotMatch(sprite,/<circle|<text|<image/);
const cleaner=fs.readFileSync(path.join(__dirname,'apu-egt-static-needle-cleaner-v1.js'),'utf8');
assert.match(cleaner,/OH12-BUS-TRANS-09319c17e7d0.png/);
assert.match(cleaner,/1024,HEIGHT=1536/);
assert.match(cleaner,/B737APUEGTStaticCleaner/);
assert.match(cleaner,/apuAmpsFootprint/);
const ui=fs.readFileSync(path.join(__dirname,'apu-egt-needle-unified.js'),'utf8');
assert.match(ui,/cleaner.cleanPiece\(piece\)/);
assert.ok(ui.includes(".atlas-piece[data-key=\"OH12\"]"));
assert.ok(ui.includes("new URL('./apu-egt-needle.svg?v=EGT-0002'"));
assert.ok(ui.includes('window.B737UnifiedApuEgtNeedle'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.ok(html.includes('apu-egt-static-needle-cleaner-v1.js?v=EGT-APUAMPS-CLEAN-0002'));
assert.ok(html.includes('apu-egt-needle-model.js?v=EGT-0005-USER-ZERO'));
assert.ok(html.includes('apu-live-meter-unified-v1.js?v=APU-EGT-COLDZERO3'));
assert.equal(model.needle.initialAngle,-241.5,'Cold-resting EGT pointer must align with photo-derived 0°C mark');
assert.ok(html.includes('apu-egt-needle-unified.js?v=EGT-SMOOTH-0006'));
assert.ok(html.includes('needle-motion-v1.js?v=NEEDLE-SMOOTH-0001'));
console.log('PASS: APU EGT OH12 photograph, 0..8x100 scale, unchanged pointer art/pivot, correct cold rest and cache mounts.');
