'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('./cabin-temperature-needle-model');
const atlas=JSON.parse(fs.readFileSync(path.join(__dirname,'../all-overhead/atlas-layout.json'),'utf8'));
const oh20=atlas.placements.find(piece=>piece.id===model.source.piece);
assert.ok(oh20);assert.deepEqual(oh20.sourceDimensions,[1254,1254]);
assert.deepEqual(model.pivot,{x:618,y:681});
assert.equal(model.needle.asset,'cabin-rate-needle.svg');
assert.ok(fs.existsSync(path.join(__dirname,model.needle.asset)));
assert.equal(model.needle.initialTemperature,20);
for(const tick of model.ticks)assert.equal(model.bearing(tick.celsius),tick.bearing);
assert.equal(model.temperature(-1),0);assert.equal(model.temperature(101),100);
assert.throws(()=>model.temperature(NaN));
const pos=model.placement(oh20);
assert.ok(pos.x>oh20.x&&pos.x<oh20.x+oh20.w);
assert.ok(pos.y>oh20.y+oh20.artInset.top&&pos.y<oh20.y+oh20.h);
const ui=fs.readFileSync(path.join(__dirname,'cabin-temperature-needle-unified.js'),'utf8');
assert.ok(ui.includes('piece.querySelector(\'.atlas-source-strip\')'));
assert.ok(ui.includes('model.needle.asset'));
assert.ok(ui.includes('window.B737UnifiedCabinTemperatureNeedle'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.ok(html.includes('cabin-temperature-needle-model.js?v=CTN-0001'));
assert.ok(html.includes('cabin-temperature-needle-unified.js?v=CTN-0002-AIRCON400'));
console.log('PASS: OH20 cabin temperature reuses the exact CABIN CLIMB needle asset and aligns to inset artwork.');
