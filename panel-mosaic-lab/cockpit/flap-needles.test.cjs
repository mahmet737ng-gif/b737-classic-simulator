'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const m=require('./flap-needles-model');
assert.equal(m.stops.length,9);
for(const s of m.stops)assert.equal(m.angle(s.value),s.angle);
assert.ok(m.angle(7)>m.angle(5)&&m.angle(7)<m.angle(10));
for(const v of [-1,41,Infinity,NaN,'10',null])assert.throws(()=>m.angle(v));
const c=m.make();assert.deepEqual([c.read().left,c.read().right,c.read().rightOccluded],[0,0,true]);
c.setCommon(15);assert.equal(c.read().mode,'common');assert.equal(c.read().rightOccluded,true);
c.setIndependent({left:10,right:30});assert.equal(c.read().mode,'independent');assert.equal(c.read().rightOccluded,false);
c.setIndependent({left:10,right:10});assert.equal(c.read().rightOccluded,true);
assert.throws(()=>c.setIndependent({left:15,right:99}));assert.deepEqual([c.read().left,c.read().right],[10,10]);
const ui=fs.readFileSync(path.join(__dirname,'flap-needles.js'),'utf8');
assert.ok(ui.indexOf("makePointer('R');makePointer('L')")>=0,'R is painted under L');
assert.ok(ui.includes("source={pieceId:'fo-inner'"),'Overlay mounted on existing F/O inner source');
assert.ok(ui.includes("b737:trailing-flaps"),'Common sensor bridge');
assert.ok(ui.includes("b737:flap-positions"),'Independent position bridge');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
for(const file of ['flap-needles.css','flap-needles-model.js','flap-needles.js'])assert.ok(html.includes(file),file);
console.log('PASS: flap needle overlay / R under L / common and independent positions / calibrated vector geometry');
