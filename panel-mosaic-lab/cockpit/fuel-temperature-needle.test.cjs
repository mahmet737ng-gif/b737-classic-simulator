'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const model=require('./fuel-temperature-needle-model');
const {spec,source}=model;
assert.deepEqual([spec.min,spec.max,spec.defaultCelsius,spec.minAngle,spec.maxAngle],[-40,40,10,-92,91]);
assert.equal(model.angle(0),0.5);
assert.equal(model.angle(-40),-92);
assert.equal(model.angle(40),91);
assert.equal(model.angle(10),24);
assert.equal(model.rotationDelta(10),-5);
assert.equal(model.clamp(-99),-40);
assert.throws(()=>model.clamp(NaN));
const atlas=JSON.parse(fs.readFileSync(path.join(__dirname,'../all-overhead/atlas-layout.json')));
const piece=atlas.placements.find(p=>p.id==='OH09');
assert.ok(piece,'Approved OH09 placement must exist');
assert.deepEqual([piece.sourceDimensions[0],piece.sourceDimensions[1]],[source.width,source.height]);
const p=model.placement(piece);
assert.ok(Math.abs(p.x-(piece.x+source.pivotX*piece.w/source.width))<1e-9);
assert.ok(Math.abs(p.y-(piece.y+source.pivotY*piece.h/source.height))<1e-9);
assert.ok(p.size>165&&p.size<185,'Needle length fit into approved fuel temperature gauge');
assert.ok(p.hubMaskRadius>30&&p.hubMaskRadius<40,'Original photographed hub remains unobscured');
const installed=fs.readFileSync(path.join(__dirname,'fuel-temperature-needle.svg'),'utf8');
assert.equal(crypto.createHash('sha256').update(installed).digest('hex'),'28fee9a427b9d1b2d99060f72c248878a34549d5158ff94fc5823722b1683a45','User-approved pointer asset must not be redesigned');
assert.match(installed,/rotate\(29 256 256\)/);
assert.doesNotMatch(installed,/<circle/);
const script=fs.readFileSync(path.join(__dirname,'fuel-temperature-unified.js'),'utf8');
assert.ok(script.includes('.atlas-piece[data-key="OH09"]'));
assert.match(script,/maskUnits:'userSpaceOnUse'/);
assert.match(script,/window\.B737UnifiedFuelTemperature/);
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.match(html,/fuel-temperature-needle-model\.js\?v=FTN-0002-SOURCEQA/);
assert.match(html,/fuel-temperature-unified\.js\?v=FTN-0002-SOURCEQA/);
assert.deepEqual(model.ticks.map(t=>t.celsius),[-40,-30,-20,-10,0,10,20,30,40]);
assert.deepEqual(model.ticks.map(t=>t.bearing),[-92,-69,-47.5,-24.5,.5,24,47,69,91]);
assert.equal(model.angle(-25),(-69-47.5)/2);
assert.equal(model.angle(35),(69+91)/2);
const whole=Array.from({length:81},(_,i)=>model.angle(-40+i));
assert.equal(whole.length,81);
for(let i=1;i<whole.length;i++)assert.ok(whole[i]>whole[i-1],'Must advance every Celsius step');
assert.equal(model.spec.nativeMajorTicksProvisional,true,'Do not claim source-image final signoff');
console.log('PASS: approved white fuel sprite, source-image nine major angles, 81 continuous targets, immutable OH09.');
