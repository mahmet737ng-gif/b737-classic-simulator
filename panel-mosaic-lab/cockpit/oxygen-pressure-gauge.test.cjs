'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('./oxygen-pressure-gauge-model');
const atlas=JSON.parse(fs.readFileSync(path.join(__dirname,'../all-overhead/atlas-layout.json'),'utf8'));
const upper=atlas.placements.find(piece=>piece.id==='UPPER');
assert.ok(upper);assert.deepEqual(upper.sourceDimensions,[model.source.width,model.source.height]);
assert.deepEqual(model.dial,{cx:1078,cy:636,radius:62,faceAsset:'oxygen-pressure-face.svg',needleAsset:'oxygen-pressure-needle.svg'});
assert.equal(model.initialPsi,1200);
assert.deepEqual(model.ticks.map(tick=>tick.hundredsPsi),[0,5,10,15,20]);
for(const tick of model.ticks)assert.equal(model.bearing(tick.hundredsPsi*100),tick.bearing);
assert.equal(model.pressurePsi(-1),0);assert.equal(model.pressurePsi(2100),2000);
assert.throws(()=>model.pressurePsi(NaN));
const pos=model.placement(upper);assert.ok(pos.x>upper.x&&pos.x<upper.x+upper.w);assert.ok(pos.y>upper.y&&pos.y<upper.y+upper.h);
const face=fs.readFileSync(path.join(__dirname,model.dial.faceAsset),'utf8');
const needle=fs.readFileSync(path.join(__dirname,model.dial.needleAsset),'utf8');
assert.match(face,/viewBox="0 0 512 512"/);assert.match(needle,/viewBox="0 0 512 512"/);
assert.equal((face.match(/<line /g)||[]).length,21);
for(const label of ['0','5','10','15','20'])assert.match(face,new RegExp('>'+label+'<\\/text>'));
assert.match(face,/OXY. PRESS./);assert.match(face,/PSI X 100/);
assert.match(needle,/oxNeedle/);assert.match(needle,/oxHub/);
const ui=fs.readFileSync(path.join(__dirname,'oxygen-pressure-gauge-unified.js'),'utf8');
assert.ok(ui.includes('.atlas-piece[data-key='));assert.ok(ui.includes('model.bearing(currentPsi)'));
assert.ok(ui.includes('window.B737UnifiedOxygenPressureGauge'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.ok(html.includes('oxygen-pressure-gauge-model.js?v=OXG-0001'));
assert.ok(html.includes('oxygen-pressure-gauge-unified.js?v=OXG-0001'));
console.log('PASS: crew oxygen pressure gauge and independently rotating needle fit the frozen UPPER crew-oxygen aperture.');
