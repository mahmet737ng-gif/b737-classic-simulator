'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=__dirname;
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const index=read('index.html'),js=read('irs-isdu-frontend-v1.js'),css=read('irs-isdu-frontend-v1.css');
const asset=read('assets/irs-honeywell-fcom-keypad.svg');
assert.match(index,/irs-isdu-frontend-v1\.js/);
assert.match(index,/irs-isdu-frontend-v1\.css/);
assert.match(js,/irsIsduDialog/);
assert.match(js,/irsIsduOpen/);
assert.match(js,/data-isdu-variant/);
assert.match(js,/VISUAL ONLY|VISUAL PREVIEW/);
assert.match(js,/irs-isdu-source/);
assert.match(css,/irs-honeywell-fcom-keypad\.avif/);
const match=asset.match(/data:image\/avif;base64,([A-Za-z0-9+/=]+)/);
assert(match,'A real embedded FCOM source crop is required');
const bytes=Buffer.from(match[1],'base64');
assert(bytes.length>2000,'Original image is not an empty placeholder');
assert(bytes.includes(Buffer.from('ftypavif')),'Embedded image does not contain AVIF signature');
assert(!js.includes('B737ElectricalV7.apply')&&!js.includes('B737FMC.apply'),'Frontend must not mutate live systems');
console.log('IRS ISDU frontend smoke PASS: source crop, modal mount, variants, no backend mutation');