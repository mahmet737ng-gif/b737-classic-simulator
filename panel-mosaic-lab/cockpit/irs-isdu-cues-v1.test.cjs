class CustomEvent{constructor(name,options){this.type=name;this.detail=options.detail;}}
const emitted=[];
const window={dispatchEvent:e=>emitted.push(e),addEventListener:()=>{}};
const document={readyState:'loading',addEventListener:()=>{},querySelector:()=>null};
vm.runInNewContext(js,{window,document,CustomEvent,MutationObserver:class{}},{timeout:1000});
const cues=window.B737ISDUCues;
assert(cues,'Visual cue API missing');
assert.deepEqual(Array.from(cues.getState().ENT),[false,false]);
assert.deepEqual(Array.from(cues.getState().CLR),[false,false]);
cues.setCueLamp('ENT','left',true);
assert.deepEqual(Array.from(cues.getState().ENT),[true,false]);
cues.setCueLamp('ENT',1,true);
assert.deepEqual(Array.from(cues.getState().ENT),[true,true]);
cues.setCue('CLR',true);
assert.deepEqual(Array.from(cues.getState().CLR),[true,true]);
cues.setCueLamp('CLR','right',false);
assert.deepEqual(Array.from(cues.getState().CLR),[true,false]);
assert.throws(()=>cues.setCueLamp('ENT','middle',true),/Unknown/);
assert.throws(()=>cues.setCueLamp('ENG',0,true),/Unknown/);
assert.throws(()=>cues.setCue('ENT',1),/boolean/);
assert.equal(emitted.at(-1).type,'b737:irs-cue-visual-change');
assert.equal(emitted.at(-1).detail.frontendOnly,true);
cues.reset();
assert.deepEqual(Array.from(cues.getState().ENT),[false,false]);
assert.deepEqual(Array.from(cues.getState().CLR),[false,false]);
