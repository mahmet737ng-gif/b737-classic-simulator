'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const model=require('./airspeed-pointers-model');
const assembly=JSON.parse(fs.readFileSync(path.join(__dirname,'assembly.json'),'utf8'));
const captain=assembly.regions.find(region=>region.id==='main').placements.find(piece=>piece.id==='captain');
const fo=assembly.regions.find(region=>region.id==='main').placements.find(piece=>piece.id==='fo-inner');
const asset=assembly.assets[captain.asset];
assert.deepEqual(asset.dimensions,[model.source.width,model.source.height]);
assert.deepEqual(model.pivot,{x:1108,y:973});
assert.deepEqual(assembly.assets[fo.asset].dimensions,[model.firstOfficer.width,model.firstOfficer.height]);
assert.deepEqual(model.firstOfficer.pivot,{x:741,y:577});
assert.equal(model.pointers.airspeed.initialKts,60);
assert.equal(model.pointers.vmoMmo.initialKts,340);
for(const tick of model.ticks)assert.equal(model.bearing(tick.kts),tick.bearing);
for(const tick of model.firstOfficerTicks)assert.equal(model.bearing(tick.kts,'firstOfficer'),tick.bearing);
assert.equal(model.speed(50),60);assert.equal(model.speed(500),400);
assert.throws(()=>model.speed(NaN));
assert.ok(model.vmoBearing(340)<0);
const pos=model.placement(captain);assert.ok(pos.x>captain.x&&pos.x<captain.x+captain.w);assert.ok(pos.y>captain.y&&pos.y<captain.y+captain.h);
const air=fs.readFileSync(path.join(__dirname,model.pointers.airspeed.asset),'utf8');
const vmo=fs.readFileSync(path.join(__dirname,model.pointers.vmoMmo.asset),'utf8');
for(const svg of [air,vmo])assert.match(svg,/viewBox="0 0 1024 1024"/);
assert.match(air,/fill="#f5f4eb"/);assert.match(air,/fill="#121414"/);
assert.match(vmo,/vmoBarber/);assert.match(vmo,/#c15c57/);
const ui=fs.readFileSync(path.join(__dirname,'airspeed-pointers-unified.js'),'utf8');
assert.ok(ui.includes('model.source.piece'));assert.ok(ui.includes('model.firstOfficer'));
assert.ok(ui.includes('model.firstOfficer'));assert.ok(ui.includes('stations[station].blades.vmoMmo=pointer('));assert.ok(ui.includes('stations[station].blades.airspeed=pointer('));
assert.ok(ui.includes('window.B737UnifiedAirspeedPointers'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.ok(html.includes('airspeed-pointers-model.js?v=ASP-0002'));
assert.ok(html.includes('airspeed-pointers-unified.js?v=ASP-0002'));
console.log('PASS: separate captain and first-officer IAS and VMO/MMO pointers register to both frozen gauges.');
