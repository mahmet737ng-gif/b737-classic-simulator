'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=__dirname, M=require('./ac-dc-selector-model-v1.js');
const DC=['STBY PWR','BAT BUS','BAT','APU BAT','TR1','TR2','TR3'];
const AC=['STBY PWR','GND PWR','GEN1','APU GEN','GEN2','INV','TEST'];
assert.deepEqual(M.detents.DC,DC,'owner-confirmed clockwise DC rotation');
assert.deepEqual(M.detents.AC,AC,'owner-confirmed clockwise AC rotation');
assert.equal(M.detents.DC.length,7);
assert.equal(M.detents.AC.length,7);
assert.equal(M.detents.DC.includes('TEST'),false,'DC must include APU BAT instead of TEST');
assert.equal(M.detents.AC.includes('GRD PWR'),false,'AC plate calls ground power GND PWR');
assert.deepEqual(M.angles,[-135,-90,-45,0,45,90,135]);
for(const side of ['DC','AC']){
 const names=M.detents[side];
 for(let i=0;i<7;i++){
  assert.equal(M.indexOf(side,names[i]),i);
  assert.equal(M.label(side,i),names[i]);
  assert.equal(M.fromAngle(side,M.angle(side,i)),i);
  if(i>0)assert.ok(M.angle(side,i)>M.angle(side,i-1),'physical clockwise order');
 }
 assert.equal(M.fromAngle(side,-999),0);
 assert.equal(M.fromAngle(side,999),6);
}
const state=M.create();
assert.equal(state.snapshot().readings.dcVolts,null,'no invented battery voltage');
assert.equal(state.snapshot().readings.cps,null,'no invented frequency');
assert.equal(state.read('DC').position,'BAT');
assert.equal(state.read('AC').position,'GEN1');
state.choose('DC','STBY PWR');state.step('DC',-1);
assert.equal(state.read('DC').position,'STBY PWR','hard left stop');
state.choose('DC','TR3');state.step('DC',1);
assert.equal(state.read('DC').position,'TR3','hard right stop');
state.choose('AC','TEST');state.step('AC',1);
assert.equal(state.read('AC').position,'TEST','AC stops at TEST');
assert.throws(()=>state.choose('DC','TEST'));
assert.throws(()=>state.choose('AC','GRD PWR'));
assert.throws(()=>state.step('AC',1.5));
state.setSourceMeasurement('DC','TR1',{volts:28.1,amps:12.7});
state.choose('DC','TR1');
assert.equal(state.readings().dcVolts,28.1);
assert.equal(state.readings().dcAmps,12.7);
state.setSourceMeasurement('AC','GEN1',{volts:115,cps:400});
state.choose('AC','GEN1');
assert.equal(state.readings().acVolts,115);
assert.equal(state.readings().cps,400);
state.choose('AC','GEN2');
assert.equal(state.readings().acVolts,null,'unmeasured source must not reuse other generator');
assert.equal(state.readings().dcVolts,28.1,'AC selector does not change DC channel');
state.setSourceMeasurement('DC','BAT BUS',{volts:24.6,amps:99});
state.choose('DC','BAT BUS');
assert.equal(state.readings().dcVolts,24.6);
assert.equal(state.readings().dcAmps,null,'battery bus has no implied ammeter measurement');
state.choose('DC','APU BAT');
assert.equal(state.readings().dcVolts,null,'APU battery cannot be fabricated');
assert.throws(()=>state.setSourceMeasurement('DC','BAT',{hz:400}));
assert.throws(()=>state.setSourceMeasurement('AC','INV',{cps:Infinity}));
const runtime=fs.readFileSync(path.join(root,'ac-dc-selectors-unified-v1.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const photoStage=fs.readFileSync(path.join(root,'../../acdc-metering-lab/photo-stage.js'),'utf8');
assert.match(runtime,/\.atlas-piece\[data-key="OH10"\]/);
assert.match(runtime,/window|B737UnifiedAcDcSelectors/);
assert.match(runtime,/setReadings\(controls.readings\(\),\{acVoltsMode:'NORMAL'\}\)/);
assert.match(runtime,/b737:ac-dc-source-measurement/);
assert.match(runtime,/addEventListener\('wheel'/);
assert.match(runtime,/addEventListener\('pointermove'/);
assert.match(runtime,/setPointerCapture/);
assert.match(runtime,/touchAction:'none'/);
assert.match(runtime,/background:'transparent'/,'must not redraw protected photo knob');
assert.match(runtime,/No synthetic|no artificial volts|no invented/i);
assert.ok(html.indexOf('ac-dc-metering-unified.js?v=')<html.indexOf('ac-dc-selector-model-v1.js?v='),
 'selector loads after existing needle backend');
assert.ok(html.indexOf('ac-dc-selector-model-v1.js?v=')<html.indexOf('ac-dc-selectors-unified-v1.js?v='));
assert.match(html,/ac-dc-selector-model-v1\.js\?v=ACDC-DETENT-0001/);
assert.match(html,/ac-dc-selectors-unified-v1\.js\?v=ACDC-DETENT-0001/);
assert.match(photoStage,/\["STBY PWR","BAT BUS","BAT","APU BAT","TR1","TR2","TR3"\]/);
assert.match(photoStage,/\["STBY PWR","GND PWR","GEN1","APU GEN","GEN2","INV","TEST"\]/);
assert.doesNotMatch(runtime,/new Image|<svg|dialScale|needle\.svg|createElementNS/);
console.log('PASS owner OH10 7+7 physical detents, stops, measurement feeds, untouched photo and native gauge linkage');
