'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const contract=JSON.parse(fs.readFileSync(path.join(__dirname,'../../engine/contracts/irs-isdu-fcom-modes-v1.json'),'utf8'));
assert.equal(contract.schema,'b737-classic.isdu.display-modes.fcom.v1');
assert.equal(contract.implementation,'REFERENCE_ONLY_DO_NOT_ASSERT_LIVE_IRS');
assert.deepEqual(contract.validModesClockwise,['TEST','TK/GS','PPOS','WIND','HDG/STS']);
assert.equal(contract.displayFormat.characters,13);
assert.equal(contract.displayFormat.latitudeFieldPositions,6);
assert.equal(contract.displayFormat.longitudeFieldPositions,7);
assert.equal(contract.displayFormat.topIndicatorLights,4);
assert.equal(contract.displayFormat.bottomFractionIndicatorLights,2);
assert.equal(contract.modes.TEST.returnsTo,'TK/GS');
assert.equal(contract.modes.TEST.requiresActualAlignStateForRealSimulation,true);
assert.equal(contract.modes['TK/GS'].upperField.name,'TRUE_TRACK');
assert.equal(contract.modes['TK/GS'].lowerField.units,'knots');
assert.equal(contract.modes.PPOS.upperField.name,'PRESENT_LATITUDE');
assert.equal(contract.modes.PPOS.lowerField.name,'PRESENT_LONGITUDE');
assert.equal(contract.modes.WIND.upperField.name,'INFLIGHT_TRUE_WIND_DIRECTION');
assert.equal(contract.modes.WIND.lowerField.units,'knots');
assert.equal(contract.modes['HDG/STS'].upperField.name,'TRUE_HEADING');
assert.match(contract.modes['HDG/STS'].duringAlignment.remainingMinutes,/9 minutes/);
assert.equal(contract.leftRightSource.L,'left IRS');
assert.equal(contract.leftRightSource.R,'right IRS');
assert.match(contract.keyboard.overrideDisplay,/overrides/);
assert.match(contract.keyboard.CLR.whiteCue,/unsuccessful ENT/);
assert.match(contract.keyboard.ENT.whiteCue,/N\/S\/E\/W/);
assert.equal(contract.futureIntegration.mustNotFabricateLiveNav.startsWith('Show invalid'),true);
console.log('PASS IRS FCOM mode schema: 5 ordered selectors, 13 display cells, 6 indicator dots, engineering source/validity boundaries');
