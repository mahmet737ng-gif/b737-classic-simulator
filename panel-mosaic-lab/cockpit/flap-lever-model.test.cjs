'use strict';
const assert=require('node:assert/strict');
const model=require('./flap-lever-model');
const values=[0,1,2,5,10,15,25,30,40];
assert.deepEqual(model.DETENTS,values);
assert.deepEqual(model.GATES,[1,15]);
assert.equal(model.gatedTarget(0,25),1,'0 → 25 first click stops at gate 1');
assert.equal(model.gatedTarget(1,25),15,'second click stops at gate 15');
assert.equal(model.gatedTarget(15,25),25,'third click reaches 25');
assert.equal(model.gatedTarget(25,0),15,'reverse first click stops at 15');
assert.equal(model.gatedTarget(15,0),1,'reverse second click stops at 1');
assert.equal(model.gatedTarget(1,0),0,'reverse third click reaches UP');
assert.deepEqual(model.sequence(1,25),[2,5,10,15],'animation ends at 15; no bypass');
assert.deepEqual(model.sequence(15,0),[10,5,2,1],'reverse stops at 1');
assert.equal(model.gatedTarget(2,10),10,'no extra stop inside one gate span');
assert.equal(model.gatedTarget(2,40),15,'a long click cannot bypass 15');
assert.equal(model.gatedTarget(40,2),15,'reverse cannot bypass 15');
assert.equal(model.swipe(0,-1),0);assert.equal(model.swipe(40,+1),40);
assert.deepEqual(values.slice(0,-1).map(v=>model.swipe(v,+1)),values.slice(1));
assert.deepEqual(values.slice(1).map(v=>model.swipe(v,-1)),values.slice(0,-1));
const texture={x:272,y:0,w:606,h:740.9857819905213,sourceWindow:{x:20,y:30,w:1055,h:1290}};
const p=model.nativePoint(texture,{x:816,y:770});
assert.ok(p.x>720&&p.x<750&&p.y>410&&p.y<440);
for(const requested of values) assert.ok(values.includes(model.gatedTarget(0,requested)));
assert.throws(()=>model.gatedTarget(0,3),/Unknown B737 FLAP detent/);
const newTexture={x:272,y:0,w:606,h:740.9857819905213,sourceWindow:{x:0,y:0,w:800,h:978.1990521327015}};
const targetRows={"0":{x:606,y:327},"1":{x:606,y:387},"2":{x:606,y:448},"5":{x:606,y:502},"10":{x:606,y:574},"15":{x:606,y:624},"25":{x:606,y:671},"30":{x:606,y:717},"40":{x:606,y:772}};
for(const value of values){
  const from=model.nativePoint(newTexture,targetRows["0"]).y;
  const to=model.nativePoint(newTexture,targetRows[String(value)]).y;
  assert.equal(model.draggedTarget(0,to-from,newTexture,targetRows),value);
}
assert.equal(model.gatedTarget(0,model.draggedTarget(0,400,newTexture,targetRows)),1,'drag cannot bypass flap gate 1');
assert.equal(model.gatedTarget(2,40),15,'drag cannot bypass flap gate 15');
console.log('PASS: nine FLAP detents, mechanical gates 1 and 15, forward/reverse click and stepwise swipes, photo alignment.');
