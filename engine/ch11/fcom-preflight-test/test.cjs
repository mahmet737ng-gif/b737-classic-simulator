'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const model=require('./model.js');
const estimator=require('../../../cdu-standalone-v6/data/epfsi-simulated-n1-v19.js');
const map=require('../data/cdu-map.json');
const source=require('../fmc-preflight-perflimits-n1limit-2023.rules.v1.json');
const dir=__dirname;
assert.equal(map.controls.length,70);assert.equal(map.outputs.length,5);assert.deepEqual(map.artwork_pixels,[1199,1312]);
assert.equal(map.artwork_sha256,'2c60c534e6e9cd80afa721f2d82801d7bdbc54dce4bbd39b8adb3470f2df0237');
assert.equal(source.rules.length,46);assert.equal(source.source.images.length,4);
assert.deepEqual(source.source.images.map(x=>x.pdf_page),[1596,1597,1599,1600]);
assert.equal(source.source.images[0].sha256,'088e8afb2720971bc505c9fda3020c5ed84c65ccab005952700b1e96a9a58634');
assert.equal(new Set(source.rules.map(x=>x.id)).size,46);
assert.ok(source.rules.every(r=>source.source.images.some(i=>i.id===r.source_image_id)));
const s=model.makeState();
assert.equal(s.page,'IDENT');assert.equal(s.guidanceEnabled,false);
assert.equal(model.view(s,estimator).rows[0][3],'20K');
function press(k){model.press(s,'CDU_CAPT_'+k);}
function type(v){for(const c of v)press(c==='.'?'KEY_DOT':c==='/'?'KEY_SLASH':'KEY_'+c);}
press('RTE');type('OIII');press('LSK_L1');type('OIIE');press('LSK_R1');
assert.equal(s.origin,'OIII');assert.equal(s.dest,'OIIE');assert.equal(s.routePending,true);
press('EXEC');assert.equal(s.routeActive,false);
press('LSK_R6');assert.equal(s.routeArmed,true);
press('EXEC');assert.equal(s.routeActive,true);assert.equal(s.routeArmed,false);
press('DEP_ARR');press('LSK_L1');assert.equal(s.page,'DEPARTURES');
assert.equal(model.view(s,estimator).rows[0][1],'NO VERIFIED DB');
press('LSK_L1');assert.equal(s.message,'SID DB NOT CONNECTED');
model.navigate(s,'PERF_INIT');
assert.equal(model.view(s,estimator).count,'1/2');
type('200');press('LSK_L5');assert.equal(s.performance.CI,'200');
type('201');press('LSK_L5');assert.equal(s.message,'INVALID ENTRY');assert.equal(s.performance.CI,'200');
press('KEY_CLR');press('KEY_CLR');press('KEY_CLR');type('12.0');press('LSK_L2');assert.equal(s.performance.FUEL,'12.0');
type('38.0');press('LSK_L3');assert.equal(s.performance.ZFW,'38.0');assert.equal(s.performance.GW,'50.0');
press('NEXT_PAGE');assert.equal(s.page,'PERF_LIMITS');
type('5');press('LSK_L1');assert.equal(s.limits.TIME_TOL,'5');
model.setTolerance(s,'OPTION_15S_ACARS');type('5');press('LSK_L1');assert.equal(s.message,'INVALID ENTRY');
press('KEY_CLR');type('6');press('LSK_L1');assert.equal(s.limits.TIME_TOL,'6');
press('LSK_R5');assert.equal(s.message,'ACARS NOT CONNECTED');
model.setVariant(s,'PLAN_FUEL_N1_LIMIT_ACARS');model.navigate(s,'PERF_INIT');assert.equal(model.view(s,estimator).rows[1][0],'PLAN/FUEL');
press('LSK_R5');assert.equal(s.message,'ACARS NOT CONNECTED');
model.setVariant(s,'FUEL_TAKEOFF');assert.equal(model.view(s,estimator).rows[5][2],'TAKEOFF>');
model.setVariant(s,'FUEL_N1_LIMIT');press('LSK_R6');assert.equal(s.page,'N1_LIMIT');
const first=model.estimateN1(s,estimator);assert.ok(first>80&&first<=95);
press('LSK_L4');assert.equal(s.thrust.takeoff,'TO-1');assert.equal(s.thrust.climb,'CLB-1');
assert.ok(model.estimateN1(s,estimator)<first);
type('45');press('LSK_L1');assert.equal(s.performance.SEL_TEMP,'45');assert.ok(model.estimateN1(s,estimator)<first);
press('LSK_L6');assert.equal(s.page,'PERF_INIT');
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8'),js=fs.readFileSync(path.join(dir,'app.js'),'utf8');
assert.ok(html.includes('../assets/cdu-approved-unlit.png'));
assert.ok(html.includes('../../../assets/fonts/boeing-cdu/cdu-screen.css'));
assert.ok(html.includes('../data/cdu-map.js'));
assert.ok(html.includes('CDU FCOM Preflight Live Test'));
assert.ok(js.includes('map.controls?.length!==70'));
console.log('PASS: original CDU visual/map, 46 FCOM rules, IDENT/RTE/EXEC, CI, ZFW/GW, PERF LIMITS variants, ACARS blocking, simulated N1 and LSK routing');
