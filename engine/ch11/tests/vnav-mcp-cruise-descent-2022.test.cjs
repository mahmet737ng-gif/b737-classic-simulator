const pathCoupling=data.variant_families.find(x=>x.id==='LNAV_VNAV_COUPLING');
assert.ok(pathCoupling);assert.equal(pathCoupling.status,'MUTUALLY_ALTERNATIVE_NOT_COMBINED');
assert.ok(data.guidelines.some(x=>x.includes('BoeingCDULarge')));
assert.equal(data.applicability.state,'EXTRACTED_NOT_EXECUTED');
console.log('PASS: '+data.rules.length+' FCOM cruise/descent/MCP specifications, 7 page anchors, variant separation and no runtime activation');
