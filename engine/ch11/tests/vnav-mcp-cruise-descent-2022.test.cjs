const data=require('../vnav-mcp-cruise-descent-2022.rules.v1.json');
assert.equal(data.schema,'b737-classic-ch11-mcp-cruise-descent-vnav-source/1.0');
assert.equal(data.source.screen_grabs.length,7);
assert.deepEqual(data.source.screen_grabs.map(x=>x.pdf_viewer_page),[1515,1516,1517,1518,1519,1520,1521]);
assert.deepEqual(data.source.screen_grabs.map(x=>x.printed_folio),['11.31.26','11.31.27','11.31.28','11.31.29','11.31.30','11.31.31','11.31.32']);
assert.equal(data.source.screen_grabs[0].sha256,'4bb870a1b9db47e8b981831c50095437be7759a0f743f514aba12c79d2663588');
assert.equal(data.source.screen_grabs[6].sha256,'ac8d8b45ec5856117ddf1d0edf9e5456ecaf464dbb4dfc05445f88e2e0d87adc');
