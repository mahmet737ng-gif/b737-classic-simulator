'use strict';
const assert=require('node:assert/strict');
const M=require('./autobrake-classic-v1.js');
const fresh=()=>M.create();
assert.deepEqual(M.DETENTS,['RTO','OFF','1','2','3','MAX']);
assert.equal(M.RTO_TEST_MS,1500);
let x=fresh();
assert.equal(x.getState().disarmLight,false);
x.select('RTO');assert.equal(x.getState().phase,'SELF_TEST');
assert.equal(x.getState().disarmLight,true);
x.advance(1499);assert.equal(x.getState().disarmLight,true);
x.advance(1);assert.equal(x.getState().phase,'WAITING');
assert.equal(x.getState().disarmLight,false);
x.update({wheelSpeedKnots:80,thrustIdle:false});
assert.equal(x.getState().phase,'ARMED');
x.update({thrustIdle:true});
assert.equal(x.getState().phase,'DISARMED');
assert.equal(x.getState().reason,'RTO_REJECT_BELOW_90');
assert.equal(x.getState().disarmLight,true);
x.select('OFF');assert.equal(x.getState().disarmLight,false);
x.update({wheelSpeedKnots:0,thrustIdle:true});
x.select('RTO');x.advance(1500);
x.update({wheelSpeedKnots:100,thrustIdle:false});
x.update({thrustIdle:true});assert.equal(x.getState().phase,'ACTIVE');
assert.equal(x.getState().disarmLight,false);
x.update({manualBrakesApplied:true});assert.equal(x.getState().reason,'MANUAL_BRAKES');
assert.equal(x.getState().disarmLight,true);
x.select('OFF');x.update({manualBrakesApplied:false,wheelSpeedKnots:0});
x.select('RTO');x.update({antiskidOn:false});x.advance(1500);
assert.equal(x.getState().phase,'FAILED');
assert.equal(x.getState().disarmLight,true);
x.select('OFF');assert.equal(x.getState().disarmLight,false);
x.update({antiskidOn:true,antiskidFault:true});
x.select('2');assert.equal(x.getState().phase,'FAILED');
x.select('OFF');x.update({antiskidFault:false});
x.select('2');assert.equal(x.getState().phase,'WAITING');
x.update({onGround:false});
x.update({onGround:true,mainWheelSpinup:true,thrustIdle:true});
assert.equal(x.getState().phase,'ACTIVE');
x.update({speedBrakeDown:true});
assert.equal(x.getState().reason,'SPEEDBRAKE_STOWED');
assert.equal(x.getState().disarmLight,true);
x.select('OFF');x.update({speedBrakeDown:false,mainWheelSpinup:false,onGround:false});
x.select('3');x.update({onGround:true,mainWheelSpinup:true,thrustIdle:true});
assert.equal(x.getState().phase,'ACTIVE');
x.update({thrustIdle:false});assert.equal(x.getState().phase,'ACTIVE','3s landing thrust grace');
x.advance(2999);assert.equal(x.getState().phase,'ACTIVE');
x.advance(1);assert.equal(x.getState().phase,'DISARMED');
x.select('OFF');x.update({mainWheelSpinup:false,thrustIdle:true,onGround:false});
x.select('MAX');x.update({onGround:true,mainWheelSpinup:true});
assert.equal(x.getState().phase,'ACTIVE');
x.update({manualBrakePressurePsi:800,wheelSpeedKnots:30});
x.advance(299);assert.equal(x.getState().phase,'ACTIVE');
x.advance(1);assert.equal(x.getState().reason,'MANUAL_BRAKE_PRESSURE');
x.select('OFF');x.update({onGround:true,manualBrakePressurePsi:0,mainWheelSpinup:false,thrustIdle:true});
x.select('RTO');x.advance(1500);x.update({onGround:false});
assert.equal(x.getState().reason,'RTO_LIFTOFF_NO_LIGHT');
assert.equal(x.getState().disarmLight,false);
x.update({onGround:true});assert.equal(x.getState().disarmLight,false);
x.advance(119999);assert.equal(x.getState().disarmLight,false);
x.advance(1);assert.equal(x.getState().reason,'LANDED_WITH_RTO_SELECTED');
assert.equal(x.getState().disarmLight,true);
x.select('OFF');assert.equal(x.getState().disarmLight,false);
x.update({solenoidPressurePsi:1200});
assert.equal(x.getState().disarmLight,true,'OFF position does not mask stuck solenoid high pressure');
x.update({solenoidPressurePsi:0});assert.equal(x.getState().disarmLight,false);
x.select('RTO');x.advance(1500);assert.equal(x.getState().phase,'WAITING');
x.update({hydraulicBAvailable:false});assert.equal(x.getState().phase,'FAILED');
const invalidHighSpeed=fresh();
invalidHighSpeed.update({wheelSpeedKnots:65});invalidHighSpeed.select('RTO');
invalidHighSpeed.advance(1500);
assert.equal(invalidHighSpeed.getState().phase,'FAILED','Cannot arm RTO above 60kt at selection');
const invalidThrust=fresh();
invalidThrust.update({thrustIdle:false});invalidThrust.select('RTO');
invalidThrust.advance(1500);
assert.equal(invalidThrust.getState().phase,'FAILED','Cannot arm RTO without idle thrust');
assert.throws(()=>x.select('INVALID'),/detent/);
assert.throws(()=>x.update({wheelSpeedKnots:-1}),/sensor/);
console.log('PASS: B737CL shared autobrake: 1500 ms RTO, 60/90 kt, landing, ANTISKID, hydraulic faults, manual brake, speedbrake, 3s touchdown grace, 2min RTO landing exception.');
