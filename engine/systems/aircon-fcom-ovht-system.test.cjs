'use strict';
const assert=require('node:assert/strict');
const P=require('./pneumatics-v6.js');
const initial=()=>P.initial();
const sensor=(s,key,value)=>P.apply(s,{type:'SENSOR',key,value});
const ctrl=(s,key,value)=>P.apply(s,{type:'CONTROL',key,value});
const reset=s=>P.apply(s,{type:'TRIP_RESET'});
const out=s=>P.derive(s);
let s=initial();
assert.ok(Object.values(out(s).lamps).every(v=>v===false));
s=sensor(s,'wingBodyTestHeld',true);
assert.equal(out(s).lamps.wingBodyOverheatL,true);
assert.equal(out(s).lamps.wingBodyOverheatR,true);
assert.equal(out(s).lamps.packTripL,false);
assert.equal(out(s).lamps.packTripR,false);
assert.equal(out(s).lamps.bleedTrip1,false);
assert.equal(out(s).lamps.bleedTrip2,false);
assert.equal(out(s).bleed.engine1ValveOpen,true,'Detector test never shuts down engine bleed');
s=sensor(s,'wingBodyTestHeld',false);
assert.equal(out(s).lamps.wingBodyOverheatL,false);
assert.equal(out(s).lamps.wingBodyOverheatR,false);
s=sensor(s,'wingBodyLDetectorFailed',true);
s=sensor(s,'wingBodyTestHeld',true);
assert.equal(out(s).lamps.wingBodyOverheatL,false,'Broken left OVHT detector fails self-test');
assert.equal(out(s).lamps.wingBodyOverheatR,true,'Independent right channel passes');
s=sensor(s,'wingBodyLLeakDetected',true);
s=sensor(s,'wingBodyTestHeld',false);
assert.equal(out(s).lamps.wingBodyOverheatL,true,'True leak persists after test release');
assert.equal(out(s).lamps.wingBodyOverheatR,false);
s=sensor(s,'wingBodyLLeakDetected',false);
assert.equal(out(s).lamps.wingBodyOverheatL,false,'Non-latched wing-body indication goes out');
s=sensor(s,'bleed1Overlimit',true);
assert.equal(out(s).lamps.bleedTrip1,true);
assert.equal(out(s).bleed.engine1ValveOpen,false,'BLEED TRIP closes affected valve');
assert.equal(out(s).bleed.engine2ValveOpen,true);
s=reset(s);
assert.equal(out(s).lamps.bleedTrip1,true,'Cannot reset while temperature/pressure is still excessive');
s=sensor(s,'bleed1Overlimit',false);
assert.equal(out(s).lamps.bleedTrip1,true,'Must reset even after cause removal');
s=reset(s);
assert.equal(out(s).lamps.bleedTrip1,false);
assert.equal(out(s).bleed.engine1ValveOpen,true);
s=sensor(s,'packROverheat',true);
assert.equal(out(s).pack.R.operational,false);
assert.equal(out(s).pack.R.mixValveCommand,'FULL_COLD');
s=sensor(s,'packROverheat',false);
assert.equal(out(s).lamps.packTripR,true);
s=reset(s);
assert.equal(out(s).lamps.packTripR,false);
s=sensor(s,'ductLOverheat',true);
assert.equal(out(s).lamps.ductOverheatL,true);
assert.equal(out(s).pack.L.mixValveCommand,'FULL_COLD');
s=sensor(s,'ductLOverheat',false);
assert.equal(out(s).lamps.ductOverheatL,true);
s=reset(s);
assert.equal(out(s).lamps.ductOverheatL,false);
s=ctrl(s,'aircraftFamily','B737-400');
assert.equal(out(s).lamps.ductOverheatL,false,'400 has ZONE TEMP rather than DUCT OVERHEAT');
s=sensor(s,'packLPrimaryControlFailed',true);
assert.equal(out(s).pack400.L.recallOnly,true);
assert.equal(out(s).pack400.L.immediate,false);
assert.equal(out(s).lamps.packTripL,false,'Single channel failure must not falsely trip PACK');
s=sensor(s,'packLStandbyControlFailed',true);
assert.equal(out(s).pack400.L.immediate,true);
assert.equal(out(s).pack.L.operational,false,'Both control channels failed closes pack valve');
s=sensor(s,'packLPrimaryControlFailed',false);
s=sensor(s,'packLStandbyControlFailed',false);
assert.equal(out(s).pack400.L.immediate,false);
s=sensor(s,'zoneContOverheat',true);
assert.equal(out(s).zoneTemp400.CONT.immediate,true);
assert.equal(out(s).zoneTemp400.CONT.trimValveClosed,true);
assert.equal(out(s).zoneTemp400.FWD.immediate,false);
s=sensor(s,'zoneContOverheat',false);
assert.equal(out(s).zoneTemp400.CONT.immediate,true);
s=reset(s);
assert.equal(out(s).zoneTemp400.CONT.immediate,false);
s=sensor(s,'contPrimaryTempControlFailed',true);
assert.equal(out(s).zoneTemp400.CONT.recallOnly,true);
assert.equal(out(s).zoneTemp400.CONT.immediate,false);
s=sensor(s,'contStandbyTempControlFailed',true);
assert.equal(out(s).zoneTemp400.CONT.immediate,true);
s=sensor(s,'fwdTempControlFailed',true);
assert.equal(out(s).zoneTemp400.FWD.recallOnly,true);
assert.equal(out(s).zoneTemp400.FWD.immediate,false);
s=sensor(s,'zoneFwdOverheat',true);
assert.equal(out(s).zoneTemp400.FWD.immediate,true);
assert.equal(out(s).zoneTemp400.FWD.trimValveClosed,true);
s=reset(s);
assert.equal(out(s).zoneTemp400.FWD.immediate,true,'Cannot reset active 400 zone overheat');
s=sensor(s,'zoneFwdOverheat',false);
s=reset(s);
assert.equal(out(s).zoneTemp400.FWD.trimValveClosed,false);
assert.equal(out(s).zoneTemp400.FWD.recallOnly,true);
console.log('PASS: FCOM OVHT held/released, detector continuity, 300/500 duct, bleed/pack trip-reset, 400 PACK/ZONE and single-channel recall.');
