'use strict';
const assert=require('node:assert/strict');
const V7=require('./electrical-v7.js');
const GPU=require('./ground-power-header-policy-v1.js');
const cmd=(s,key,value)=>V7.apply(s,{type:'CONTROL',key,value});
const select=(s,source,side=1)=>V7.apply(s,{type:'SELECT_SOURCE',source,side});
const evaluate=s=>GPU.evaluate(s,V7.evaluate(s));
const plan=(s,action)=>GPU.plan(action,s,V7.evaluate(s));
let state=V7.initialState({coldDark:true});
assert.equal(evaluate(state).status,'DISCONNECTED');
assert.equal(evaluate(state).available,false);
assert.equal(evaluate(state).canSwitchOn,false);
assert.equal(plan(state,'CONNECT').environmentAttached,true);
state=cmd(state,'groundPowerAttached',true);
assert.equal(evaluate(state).available,true,'GPU AVAILABLE must be illuminated with cable and quality');
assert.equal(evaluate(state).canSwitchOn,false,'BATTERY OFF inhibits GRD PWR ON');
assert.throws(()=>plan(state,'ON'),/BATTERY_SWITCH_OFF/);
assert.equal(V7.evaluate(state).bus.transfer1,false,'Cable alone cannot power airplane');
state=cmd(state,'batterySwitch',true);
assert.equal(evaluate(state).canSwitchOn,true);
assert.deepEqual(plan(state,'ON').sourceCommands,[{type:'SELECT_SOURCE',side:1,source:'EXT'}]);
state=select(state,'EXT');
assert.equal(evaluate(state).status,'ON_BUS');
assert.equal(evaluate(state).connected,true);
assert.equal(state.source[1],'EXT');
assert.equal(state.source[2],'EXT');
assert.equal(V7.evaluate(state).bus.transfer1,true);
assert.equal(V7.evaluate(state).bus.transfer2,true);
assert.equal(V7.evaluate(state).lamps.busOff1,false);
assert.equal(V7.evaluate(state).lamps.busOff2,false);
assert.equal(V7.evaluate(state).lamps.transferBusOff1,false);
assert.equal(V7.evaluate(state).lamps.transferBusOff2,false);
assert.equal(V7.evaluate(state).lamps.standbyPowerOff,false);
assert.equal(V7.evaluate(state).lamps.groundPowerAvailable,true);
assert.deepEqual(plan(state,'OFF').sourceCommands,[
 {type:'SELECT_SOURCE',side:1,source:'OFF'},
 {type:'SELECT_SOURCE',side:2,source:'OFF'}
]);
state=select(select(state,'OFF',1),'OFF',2);
assert.equal(evaluate(state).available,true,'GRD POWER AVAILABLE remains with cable');
assert.equal(evaluate(state).connected,false);
assert.equal(evaluate(state).status,'AVAILABLE');
state=select(state,'EXT');
state=cmd(state,'batterySwitch',false);
assert.deepEqual(state.source,{1:null,2:null},'BAT OFF automatically drops external contactors');
state=cmd(state,'batterySwitch',true);
assert.equal(evaluate(state).connected,false,'BAT ON cannot auto-reconnect GPU');
state=select(state,'EXT');
state=cmd(state,'groundPowerAttached',false);
assert.deepEqual(state.source,{1:null,2:null},'GPU unplug trips both contactors');
state=cmd(state,'groundPowerAttached',true);
assert.equal(evaluate(state).connected,false,'Replug requires GRD PWR ON again');
state=select(state,'EXT');
state=cmd(state,'groundPowerQualityGood',false);
assert.deepEqual(state.source,{1:null,2:null},'Rejected quality disconnects GPU');
assert.equal(evaluate(state).status,'BAD_QUALITY');
assert.throws(()=>plan(state,'ON'),/POWER_QUALITY_NOT_ACCEPTABLE/);
state=cmd(state,'groundPowerQualityGood',true);
assert.equal(evaluate(state).connected,false,'Quality recovery cannot auto-reconnect');
state=select(state,'EXT');
state=cmd(state,'onGround',false);
assert.deepEqual(state.source,{1:null,2:null},'GPU not selected while airborne');
assert.throws(()=>plan(state,'CONNECT'));
state=cmd(state,'onGround',true);
state=cmd(state,'groundServiceSelected',true);
state=cmd(state,'batterySwitch',false);
assert.equal(V7.evaluate(state).bus.groundService,true,'Classic ground service can feed service bus without airplane AC');
assert.equal(V7.evaluate(state).bus.transfer1,false);
state=cmd(state,'batterySwitch',true);
state=select(state,'EXT');
assert.equal(state.config.groundServiceSelected,false,'GRD PWR ON overrides ground service');
assert.equal(V7.evaluate(state).source[1],'EXT');
assert.equal(V7.evaluate(state).source[2],'EXT');
state=cmd(state,'groundPowerAttached',false);
assert.equal(V7.evaluate(state).lamps.groundPowerAvailable,false);
assert.equal(evaluate(state).status,'DISCONNECTED');
assert.throws(()=>plan(state,'WRONG'),/Unknown ground power/);
console.log('PASS: Classic FCOM GPU AVAILABLE separate from power ON; BAT interlock; both buses; auto-trip; quality; service bus; no unwanted reselect.');
