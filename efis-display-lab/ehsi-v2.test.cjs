'use strict';
const assert=require('node:assert/strict');
const V=require('./ehsi-v2.js');
const core=require('./core.js');
assert.equal(V.VERSION,'EHSI-CLASSIC-REBUILD-0002');
assert.deepEqual(V.MODES,['MAP','FULL_NAV','PLAN']);
assert.equal(V.LAYOUT.MAP.degrees,70);
assert.equal(V.LAYOUT.FULL_NAV.degrees,360);
assert.equal(V.LAYOUT.PLAN.rose,false);
assert.equal(V.LAYOUT.PLAN.degrees,70);
assert.equal(V.LAYOUT.PLAN.planCompass,true);
assert.equal(V.LAYOUT.MAP.roseCenter[1]>V.LAYOUT.FULL_NAV.roseCenter[1],true,'MAP airplane low, FULL NAV airplane centered');
assert.equal(V.LAYOUT.MAP.aircraft[1]>400,true);
assert.equal(V.LAYOUT.FULL_NAV.aircraft[1]<300,true);
let m=core.ehsiModel(core.initial());
assert.equal(m.selectedHeading,252);
let r=V.computeDisplay(m);
assert.equal(r.mode,'MAP');
assert.equal(r.supported,true);
assert.equal(r.has70DegreeArc,true);
assert.equal(r.hasFullCompass,false);
assert.equal(r.orientation,'TRACK_UP');
assert.equal(r.headingBugLineVisible,true);
assert.equal(r.wptDatabaseEligible,true);
assert.equal(r.routeValid,true);
m.mode='FULL_NAV';r=V.computeDisplay(m);
assert.equal(r.hasFullCompass,true);
assert.equal(r.compassHeadingReference,'HEADING');
assert.equal(r.has70DegreeArc,false);
m.mode='PLAN';r=V.computeDisplay(m);
assert.equal(r.northUp,true);
assert.equal(r.has70DegreeArc,true);
assert.equal(r.orientation,'TRUE_NORTH');
assert.equal(r.headingBugLineVisible,false);
assert.equal(r.layout.rose,false);
m.track=120;m.heading=80;
assert.equal(V.computeDisplay(m).northUp,true,'PLAN must not rotate with track/heading');
m.mode='MAP';m.range=80;
assert.equal(V.computeDisplay(m).wptDatabaseEligible,false,'WPT database map option gated above 40 NM');
m.range=40;
assert.equal(V.computeDisplay(m).wptDatabaseEligible,true);
m.nav.valid=false;
assert.equal(V.computeDisplay(m).routeValid,false,'NAV failure invalidates route');
m.nav.valid=true;m.efis.trackValid=false;
assert.equal(V.computeDisplay(m).routeValid,false,'Track-up requires valid reference');
m.efis.trackValid=true;m.efis.headingValid=false;
assert.equal(V.computeDisplay(m).orientationValid,false);
m.efis.headingValid=true;m.efis.sgValid=false;
assert.equal(V.computeDisplay(m).sgValid,false);
m.efis.sgValid=true;m.efis.displayPower=false;
assert.equal(V.computeDisplay(m).powered,false);
m.efis.displayPower=true;
m.mode='FULL_VOR_ILS';
assert.equal(V.computeDisplay(m).supported,false,'Do not render generic VOR fallback');
assert.equal(V.computeDisplay(m).approval,'VISUAL_REFERENCE_PIXEL_QA_PENDING');
assert.equal(V.norm(-12),348);
assert.equal(V.rel(355-5),-10);
assert.ok(V.REFERENCE.MAP.includes('10.31.2'));
assert.ok(V.REFERENCE.FULL_NAV.includes('10.31.8'));
assert.ok(V.REFERENCE.PLAN.includes('10.31.18'));
console.log('PASS EHSI v2: mode geometry, orientation, flags, WPT range and provisional source status.');
