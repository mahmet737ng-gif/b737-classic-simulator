'use strict';
const assert=require('node:assert/strict');
const V=require('./ehsi-v2.js');
const core=require('./core.js');
const evidence=require('./sources.js');
const start=core.initial();
const set=(s,path,value)=>core.apply(s,{type:'set',path,value});
const option=(s,name,value)=>core.apply(s,{type:'option',name,value});
const scenario=name=>core.apply(start,{type:'scenario',name});
const view=s=>V.computeDisplay(core.ehsiModel(s));
assert.equal(V.VERSION,'EHSI-CLASSIC-REBUILD-0011-FCOM-1031-FULL-NAV');
assert.equal(V.MODES.length,7);
assert.equal(evidence.sections.length,16);
for(const mode of core.MODES)assert.equal(view(set(start,'ehsi.mode',mode)).supported,true);
assert.equal(V.LAYOUT.MAP.degrees,70);
assert.equal(V.LAYOUT.CTR_MAP.degrees,360);
assert.equal(view(set(start,'ehsi.mode','CTR_MAP')).hasFullCompass,true);
const map=V.LAYOUT.MAP,ctr=V.LAYOUT.CTR_MAP;
assert.deepEqual(map.aircraft,[256,418]);
assert.deepEqual(V.rosePoint(map,0),[256,85]);
assert.deepEqual(V.rosePoint(map,0,.5),[256,251.5]);
assert.deepEqual(ctr.aircraft,[256,302]);
assert.deepEqual(V.rosePoint(ctr,0),[256,152]);
assert.deepEqual(V.rosePoint(ctr,90),[434,302]);
assert.deepEqual(V.rosePoint(ctr,180),[256,452]);
assert.deepEqual(V.rosePoint(ctr,270),[78,302]);
assert.deepEqual(V.rosePoint(ctr,0,.5),[256,227]);
assert.deepEqual(V.rosePoint(ctr,180,.5),[256,377]);
assert.equal(core.ehsiModel(set(start,'ehsi.trueAirspeed',0)).trueAirspeed,0);
assert.equal(V.LAYOUT.FULL_NAV.degrees,360);
assert.equal(V.LAYOUT.FULL_NAV.radius,115);
assert.equal(V.LAYOUT.FULL_VOR_ILS.radius,V.LAYOUT.FULL_NAV.radius);
assert.equal(V.DISPLAY_ASPECT,350/411);
for(const mode of ['EXP_NAV','EXP_VOR_ILS','PLAN']){
 const expanded=V.LAYOUT[mode];
 assert.equal(expanded.radius,map.radius);
 assert.equal(expanded.radiusX,map.radiusX);
 assert.deepEqual(expanded.roseCenter,map.roseCenter);
 assert.equal(expanded.route,mode==='PLAN');
}
assert.deepEqual(V.LAYOUT.PLAN.aircraft,null);
assert.equal(view(start).orientation,'TRACK_UP');
assert.equal(view(start).routeValid,true);
assert.equal(view(start).wptDatabaseEligible,true);
assert.equal(view(set(start,'ehsi.range',80)).wptDatabaseEligible,false);
assert.equal(view(set(start,'ehsi.mode','FULL_NAV')).compassHeadingReference,'TRACK');
const vr=set(start,'ehsi.mode','FULL_VOR_ILS');
assert.equal(view(vr).presentation,'FULL_VOR');
assert.equal(view(vr).orientation,'HEADING_UP');
assert.equal(view(set(vr,'ehsi.navType','ILS')).presentation,'FULL_ILS');
const plan=set(start,'ehsi.mode','PLAN');
assert.equal(view(plan).orientation,'TRUE_NORTH');
assert.equal(view(plan).headingBugLineVisible,false);
assert.equal(view(set(plan,'power.track',false)).routeValid,true);
assert.equal(view(set(plan,'power.track',false)).compassValid,false);
assert.equal(view(set(start,'power.nav',false)).routeValid,false);
assert.equal(view(set(start,'power.track',false)).routeValid,false);
assert.equal(view(set(start,'power.heading',false)).routeValid,true,'valid track retains the MAP route');
assert.equal(view(set(start,'power.fmcTrack',false)).trackSource,'IRS LEFT');
assert.equal(view(set(start,'power.sg1',false)).sgValid,false);
assert.equal(view(set(start,'power.ehsi',false)).powered,false);
assert.equal(view(scenario('weather')).wxrVisible,true);
assert.equal(view(set(scenario('weather'),'power.remoteWxr',false)).wxrVisible,false);
assert.equal(view(set(scenario('weather'),'power.wxrRange',false)).wxrVisible,false);
assert.equal(view(set(scenario('weather'),'ehsi.mode','PLAN')).wxrVisible,false);
assert.equal(view(scenario('terrain')).terrainVisible,true);
assert.equal(view(option(scenario('weather'),'terr',true)).wxrVisible,false);
assert.equal(view(scenario('tcas')).trafficOverlay,true);
assert.equal(view(option(scenario('tcas'),'tfc',false)).trafficOverlay,false);
assert.equal(view(set(scenario('tcas'),'ehsi.mode','FULL_NAV')).trafficOverlay,false);
assert.equal(core.ehsiModel(set(vr,'ehsi.autoTune',true)).nav.frequency,null);
assert.equal(core.ehsiModel(set(vr,'ehsi.vorDev',5)).nav.cdi,1);
assert.equal(core.ehsiModel(set(start,'ehsi.xtk',2)).nav.cdi,1);
assert.equal(V.norm(-12),348);
assert.equal(V.rel(355-5),-10);
console.log('PASS EHSI: seven selector positions, nine presentations, sources, range, traffic, WXR and TERR.');

