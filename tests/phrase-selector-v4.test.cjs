assert.ok(!Object.values(require("../audio/policy/phrase-selector-v4.js").DIRECT).includes("a.mp3"));
const miss=p.update({oneshot:[{key:"radioAltitude|FIVE HUNDRED"}]});
assert.equal(miss.play.length,0);assert.equal(miss.missing.length,1);
assert.throws(()=>p.confirm("EGPWS-01","radioAltitude|FIVE HUNDRED"));
assert.throws(()=>p.confirm("RA-01","gpws|SINK RATE"));
p.confirm("RA-01","radioAltitude|FIVE HUNDRED");
