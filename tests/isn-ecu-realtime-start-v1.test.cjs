'use strict';
// Source-faithful gates, owner-selected (not AFM verified) ~85s APU/~100s
// engine training timeline. Old ISN-03 remains in fast instructional mode.
const assert=require('node:assert/strict');
const B=require('../engine/integration/isn-13-18-ecu-testbench-v1');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const Chain=require('../engine/integration/isn-apu-start-chain-v1');
const ThrustPlanner=require('../engine/integration/isn-thrust-performance-v1');
const FuelRuntime=require('../engine/integration/isn-09-12-runtime-v1');
const s=new B.Testbench({Electrical,Loads,TrainerCore,WarningEngine,Pneumatics,Pack,EngineAPU,Start,Chain,ThrustPlanner,FuelRuntime});
assert.equal(s.get().timingProfile,'REALTIME_TRAINING');
assert.equal(s.get().timing.apuReadyMs,85000);
assert.equal(s.get().timing.engineMotoringMs,40000);
assert.equal(s.get().timing.engineLightoffMs,50000);
assert.equal(s.get().engines.engine1.phase,'OFF');
s.battery(true);
s.startAPU();
assert.equal(s.get().apu.phase,'INLET_DOOR');
s.advance(8999);
assert.equal(s.get().apu.phase,'INLET_DOOR');
s.advance(1);
assert.equal(s.get().apu.phase,'STARTING');
s.advance(75000);
assert.equal(s.get().apu.phase,'STARTING','APU must not be READY prematurely at 84 sec');
assert.ok(s.get().apu.rpmPct>5&&s.get().apu.rpmPct<100);
s.advance(1000);
assert.equal(s.get().apu.phase,'READY');
assert.equal(s.get().apu.startElapsedSec,85);
assert.equal(s.get().apu.rpmPct,95.5);
assert.equal(s.get().apu.generator.voltageV,115);
assert.equal(s.get().apu.generator.frequencyHz,400);
s.selectGenerator('APU',1);
s.apuBleed(true);
// Engine can motor before fuel pump selection, but fuel lever must be blocked
// until both the N2 start cue AND fuel pump supply are true.
s.engineStart('engine1');
assert.equal(s.get().engines.engine1.phase,'MOTORING');
let early=s.fuelLever('engine1','IDLE');
assert.equal(early.accepted,true,'Lever IDLE is never mechanically locked by N2');
assert.equal(early.fuelAvailable,false,'Pumps OFF still prevent fuel delivery');
assert.equal(s.get().engines.engine1.fuelLever,'IDLE');
assert.equal(s.get().engines.engine1.fuelFlowKgHr,0);
s.advance(20000);
const earlyN2=s.get().engines.engine1.n2Percent;
assert.ok(earlyN2>3&&earlyN2<25,'N2 must spool, not jump to 25');
assert.ok(s.get().engines.engine1.n1Percent<7,'N1 initially low under starter is normal');
s.advance(19999);
assert.equal(s.get().engines.engine1.phase,'MOTORING');
s.advance(1);
assert.equal(s.get().engines.engine1.phase,'AWAIT_FUEL_LEVER_IDLE');
assert.ok(Math.abs(s.get().engines.engine1.n2Percent-25)<0.1);
assert.equal(s.get().engines.engine1.fuelSupplyReady===true,false);
assert.equal(s.get().engines.engine1.fuelLever,'IDLE','Lever stays IDLE even without delivery');
assert.equal(s.get().engines.engine1.fuelFlowKgHr,0);
s.prepareFuel();
assert.equal(s.get().engines.engine1.fuelSupplyReady,true);
assert.equal(s.get().engines.engine1.phase,'LIGHT_OFF_SEQUENCE','Fuel and ignition trigger lightoff after previously selected IDLE');
assert.ok(s.get().engines.engine1.fuelFlowKgHr>0);
s.advance(37500);
assert.ok(s.get().engines.engine1.egtC>=615,'Nominal light-off EGT transient should approach 620C');
assert.ok(s.get().engines.engine1.n2Percent>25);
assert.equal(s.get().engines.engine1.phase,'LIGHT_OFF_SEQUENCE');
s.advance(12499);
assert.equal(s.get().engines.engine1.phase,'LIGHT_OFF_SEQUENCE');
s.advance(1);
assert.equal(s.get().engines.engine1.phase,'RUNNING','~90s total to RUNNING with timely lever');
assert.equal(s.get().engines.engine1.startValveOpen,false);
assert.equal(s.get().engines.engine1.startElapsedSec,90);
s.advance(10000);
assert.equal(s.get().engines.engine1.startElapsedSec,100);
assert.ok(Math.abs(s.get().engines.engine1.n1Percent-22)<1);
assert.ok(Math.abs(s.get().engines.engine1.n2Percent-60)<1);
assert.equal(s.get().engines.engine1.oil.lowPressureLamp,false);
assert.ok(s.get().fuel.burnedKg.engine1>0);
assert.equal(s.get().engines.engine2.phase,'OFF');
const compStart=new Chain.Chain(s.start,{timingProfile:'CLASSROOM_COMPRESSED'});
assert.equal(compStart.timing.apuReadyMs,1400);
assert.throws(()=>new Chain.Chain(s.start,{timingProfile:'BAD'}),/Unknown ISN timing profile/);
console.log('PASS ECU SLOW START: APU 85s, engine N2 25% at 40s, early IDLE accepted mechanically, pump source required, light-off EGT ~620C, starter cutout at ~90s, stable 22/60 by ~100s.');
