'use strict';
/* ISN-13 through ISN-18 deterministic simulation QA. Node tests never alter art. */
const assert=require('node:assert/strict');
const B=require('../engine/integration/isn-13-18-ecu-testbench-v1');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const Chain=require('../engine/integration/isn-apu-start-chain-v1');
const ThrustPlanner=require('../engine/integration/isn-thrust-performance-v1');
const FuelRuntime=require('../engine/integration/isn-09-12-runtime-v1');
// Legacy compressed course tests explicitly opt in. The web ECU bench now
// defaults to the longer user-selected timing profile.
const rig=()=>new B.Testbench({Electrical,Loads,TrainerCore,WarningEngine,Pneumatics,Pack,EngineAPU,Start,Chain,ThrustPlanner,FuelRuntime,timingProfile:'CLASSROOM_COMPRESSED'});
const light=s=>s.engines.engine1.oil.lowPressureLamp;
let oil=B.oilInitial();
assert.equal(oil.lowPressureLamp,true);
assert.deepEqual([B.CONFIG.oilPressureLampOnPsi,B.CONFIG.oilPressureLampOffPsi],[12.25,15.25]);
oil=B.oilStep(oil,{n2Percent:60,engineRunning:true},10000);
assert.equal(oil.lowPressureLamp,false);
assert.ok(oil.pressurePsi>15.25);
oil.faults.pumpFailure=true;
oil=B.oilStep(oil,{n2Percent:60,engineRunning:true},30000);
assert.equal(oil.lowPressureLamp,true);
assert.ok(oil.pressurePsi<=12.25);
// Schmitt deadband: leave current light position unchanged.
const inBand={...B.oilInitial(),pressurePsi:14,lowPressureLamp:false};
assert.equal(B.oilStep(inBand,{n2Percent:13.5},0).lowPressureLamp,false);
assert.equal(B.oilStep({...inBand,lowPressureLamp:true},{n2Percent:13.5},0).lowPressureLamp,true);
assert.throws(()=>B.oilStep(oil,{n2Percent:NaN},1000));
const s=rig();
assert.equal(s.get().electrical.battery,false);
assert.equal(s.get().engines.engine1.phase,'OFF');
s.battery(true);
s.startAPU();s.advance(1400);
assert.equal(s.get().apu.phase,'READY');
s.selectGenerator('APU',1);
s.apuBleed(true);
s.prepareFuel();
assert.equal(s.get().electrical.selectedSources[1],'APU');
assert.equal(s.get().apu.bleedValveOpen,true);
s.engineStart('engine1');
assert.equal(s.get().engines.engine1.phase,'MOTORING');
s.advance(850);
assert.equal(s.get().engines.engine1.phase,'AWAIT_FUEL_LEVER_IDLE');
assert.equal(s.fuelLever('engine1','IDLE').accepted,true);
s.advance(750);
assert.equal(s.get().engines.engine1.phase,'LIGHT_OFF_SEQUENCE');
assert.equal(s.get().engines.engine1.egtC,600);
s.advance(250);
assert.equal(s.get().engines.engine1.phase,'RUNNING');
s.advance(12000);
assert.ok(s.get().engines.engine1.n1Percent>21&&s.get().engines.engine1.n1Percent<24);
assert.ok(s.get().engines.engine1.n2Percent>58);
assert.ok(s.get().engines.engine1.oil.pressurePsi>15.25);
assert.equal(light(s.get()),false);
assert.ok(s.get().fuel.burnedKg.engine1>0);
s.engineStart('engine2');s.advance(850);s.fuelLever('engine2','IDLE');s.advance(1000);s.advance(12000);
assert.equal(s.get().engines.engine2.phase,'RUNNING');
assert.equal(s.get().engines.engine2.oil.lowPressureLamp,false);
// Simulated flight high idle and N1 mode reference. Wind is ground-speed only.
s.setOnGround(false);
s.setFlightInputs({pressureAltitudeFt:10000,oatC:0,iasKt:200,massKg:55000});
s.planThrust('engine1',{mode:'CRZ',targetIasKt:240,accelTimeSec:40});
s.advance(13000);
assert.ok(s.get().engines.engine1.n1Percent>32);
assert.ok(s.get().engines.engine1.n1Percent<=97);
assert.ok(s.get().thrust.lastPlan.performance.requiredN1NowPercent>0);
// Inject failure at running N2: low oil pressure even though N2 remains stable.
s.setOilFault('engine1','pumpFailure',true);
s.advance(25000);
assert.equal(s.get().engines.engine1.oil.lowPressureLamp,true);
assert.ok(s.get().alerts.some(a=>a.id==='engine1.LOW_OIL_PRESSURE'));
assert.equal(s.get().engines.engine2.oil.lowPressureLamp,false);
s.setOilFault('engine1','pumpFailure',false);
s.setOilFault('engine1','filterRestriction',true);
s.advance(9000);
assert.ok(s.get().alerts.some(a=>a.id==='engine1.OIL_FILTER_BYPASS'));
assert.equal(s.get().engines.engine1.oil.lowPressureLamp,false);
// Shutdown must coast displayed indications and restore low oil pressure.
s.shutdown('engine1');
assert.equal(s.get().engines.engine1.phase,'OFF');
s.advance(30000);
assert.equal(s.get().engines.engine1.oil.lowPressureLamp,true);
assert.ok(s.get().engines.engine1.n1Percent<2);
assert.equal(s.get().engines.engine2.phase,'RUNNING');
assert.ok(s.get().fuel.tanksKg.main1<3500);
assert.throws(()=>s.setThrottle('engine1',0.4));
// Failed bleed path blocks ignition/motoring with APU otherwise ready.
const fail=rig();fail.battery(true);fail.startAPU();fail.advance(1400);
fail.selectGenerator('APU',1);fail.prepareFuel();
fail.setAPUFault('bleedFailure',true);
fail.engineStart('engine1');
assert.equal(fail.get().engines.engine1.phase,'BLOCKED');
// Distinct injected hot start triggers existing start chain threshold but NOT fire bell.
const hot=rig();hot.battery(true);hot.startAPU();hot.advance(1400);
hot.selectGenerator('APU',1);hot.apuBleed(true);hot.prepareFuel();
hot.setStartFault('engine1','egtHigh',true);
hot.engineStart('engine1');hot.advance(850);hot.fuelLever('engine1','IDLE');
hot.advance(960);
assert.equal(hot.get().engines.engine1.phase,'ABNORMAL_EGT');
assert.equal(hot.get().engines.engine1.phase==='RUNNING',false);
assert.ok(hot.get().alerts.some(a=>a.id.includes('ABNORMAL_START_EGT')));
assert.throws(()=>rig().setOilFault('engine3','pumpFailure',true));
assert.throws(()=>rig().advance(-1));
console.log('PASS ISN 13-18: oil pressure 12.25/15.25 Schmitt, EGT peak, cold/dark APU, dual-engine start, high idle, CDU thrust reference, fuel burn, bleed fault, pump fault, filter bypass, hot-start alarm, shutdown coastdown.');