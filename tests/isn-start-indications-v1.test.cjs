'use strict';
const assert=require('node:assert/strict');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const Chain=require('../engine/integration/isn-apu-start-chain-v1');
const {project}=require('../engine/integration/isn-start-indications-v1');
const chain=new Chain.Chain(new Start.Session({EngineAPU,ElectricalPack:Pack,Electrical,Loads,TrainerCore,WarningEngine,Pneumatics}));
let v=project(chain.get());
assert.equal(v.engines.engine1.n2.value,null,'UNKNOWN cannot become zero');
assert.equal(v.engines.engine1.n2.text,'—');
assert.equal(v.engines.engine1.egt.value,null);
assert.equal(v.engines.engine1.startValve.text,'UNKNOWN');
assert.equal(v.engines.engine1.startValve.mountedLamp,false);
chain.synchronize({toggles:{'bleed-apu':'ON','pack-l':'OFF','pack-r':'OFF','isolation-valve':'OPEN'},
 guards:{'battery-master':{value:'on'}},rotaries:{'ignition-source':'BOTH'},context:{onGround:true}});
chain.event({id:'apu-start',kind:'toggle',next:'START'});chain.advance(1400);
chain.start.core.pack.send({type:'ELECTRICAL',action:{type:'SELECT_SOURCE',source:'APU',side:1}});chain.syncPower();
chain.event({id:'engine-start-2',kind:'rotary',next:'GRD'});v=project(chain.get());
assert.equal(v.engines.engine2.startValve.text,'OPEN');
assert.equal(v.engines.engine2.startValve.amber,true);
assert.equal(v.engines.engine2.startValve.mountedLamp,true);
assert.equal(v.engines.engine2.n2.text,'0 %');
assert.equal(v.engines.engine2.egt.text,'—','do not invent EGT before fuel introduction');
assert.equal(v.engines.engine1.startValve.text,'UNKNOWN','Engine 1 remains independent');
chain.advance(850);v=project(chain.get());assert.equal(v.engines.engine2.n2.text,'25 %');
assert.equal(v.engines.engine2.n2.origin,Chain.ORIGIN);
chain.lever('engine2','IDLE');v=project(chain.get());
assert.equal(v.engines.engine2.egt.text,'0 °C');
assert.equal(v.engines.engine2.egt.origin,Chain.ORIGIN);
chain.advance(1000);v=project(chain.get());
assert.equal(v.engines.engine2.n2.text,'46 %');
assert.equal(v.engines.engine2.egt.text,'420 °C');
assert.equal(v.engines.engine2.startValve.text,'CLOSED');
assert.equal(v.engines.engine2.startValve.mountedLamp,false);
assert.equal(v.engines.engine2.running,true);
// 725 C is an abnormal-start advisory, not an automatically fabricated FIRE.
chain.feedback('engine1','egtC',725);v=project(chain.get());
assert.equal(v.engines.engine1.egt.text,'725 °C');
assert.equal(v.engines.engine1.egt725Advisory,false,'out of start window is not an abnormal-start latch');
assert.match(v.training,/TRAINING_SEQUENCE_SIMULATED/);
console.log('PASS ISN-03 Stage 3: source-tagged N2/EGT, independent valve lamps, unknown preservation and training advisory boundary.');
