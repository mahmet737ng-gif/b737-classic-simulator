assert.equal(e(x.view).secondary.oilPressurePsi.display,'NO_DATA');
assert.throws(()=>go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'n2Pct',value:30}),/authoritative/);
x=go(s,'SET_ENGINE_N2',{engine:1,value:105});s=x.state;
assert.equal(e(x.view).primary.n2Pct.value,105);
assert.equal(e(x.view).computed.n2RedLimitDemand,true);
x=go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'n1Pct',value:106});s=x.state;
assert.equal(e(x.view).computed.n1RedLimitDemand,true);
assert.equal(x.view.annunciation.lamps.ENG1_N1_LIMIT.logicalDemand,'ON');
x=go(s,'SET_ENGINE_START_LEVER',{engine:1,value:'IDLE'});s=x.state;
x=go(s,'SET_ENGINE_EGT_C',{engine:1,value:725});s=x.state;
assert.equal(e(x.view).primary.egtC.value,725);
assert.equal(e(x.view).computed.egtLimitC,725);
assert.equal(e(x.view).computed.egtLimitDemand,true);
x=go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'oilPressurePsi',value:13});s=x.state;
assert.equal(x.view.annunciation.lamps.ENG1_LOW_OIL_PRESSURE.logicalDemand,'ON');
x=go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'oilPressurePsi',value:14});s=x.state;
assert.equal(x.view.annunciation.lamps.ENG1_LOW_OIL_PRESSURE.logicalDemand,'OFF');
x=go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'oilTempC',value:163});s=x.state;
assert.equal(e(x.view).computed.oilTempZone,'CAUTION_TIME_LIMITED');
x=go(s,'ADVANCE_SECONDS',{value:901});s=x.state;
assert.equal(e(x.view).computed.oilTemp15MinExceeded,true);
x=go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'oilTempC',value:165});s=x.state;
assert.equal(e(x.view).computed.oilTempZone,'AT_OR_ABOVE_MAX');
x=go(s,'SET_INSTRUMENT_SIGNAL',{engine:1,instrument:'n1Pct',value:'SIGNAL_LOSS'});s=x.state;
assert.equal(e(x.view).primary.n1Pct.display,'LOWER_STOP');
assert.equal(x.view.annunciation.lamps.ENG1_N1_LIMIT.logicalDemand,'UNKNOWN');
x=go(s,'ADVANCE_SECONDS',{value:2});s=x.state;
assert.equal(e(x.view).primary.n1Pct.display,'DASHES');
x=go(s,'SET_INSTRUMENT_SIGNAL',{engine:1,instrument:'n1Pct',value:'INTERNAL_FAILURE'});s=x.state;
assert.equal(e(x.view).primary.n1Pct.display,'BLANK');
x=go(s,'SET_INSTRUMENT_SIGNAL',{engine:1,instrument:'n1Pct',value:'VALID'});s=x.state;
assert.equal(e(x.view).primary.n1Pct.value,106);
x=go(s,'SET_INSTRUMENT_SIGNAL',{engine:1,instrument:'oilPressurePsi',value:'SIGNAL_LOSS'});s=x.state;
assert.equal(e(x.view).secondary.oilPressurePsi.display,'DASHES_OR_BLANK');
assert.equal(e(x.view).computed.oilPressureLowLightDemand,null);
x=go(s,'SET_ENGINE_INDICATION',{engine:2,instrument:'fuelFlowKgHr',value:3600});s=x.state;
assert.equal(e(x.view,'2').primary.ffDigital.value,3.6);
x=go(s,'RESET_FUEL_USED',{engine:2});s=x.state;
x=go(s,'ADVANCE_SECONDS',{value:1});s=x.state;
assert.equal(e(x.view,'2').fuelUsedKg,0);
x=go(s,'ADVANCE_SECONDS',{value:10});s=x.state;
assert.equal(e(x.view,'2').fuelUsedKg,10);
x=go(s,'PUSH_FUEL_USED',{engine:2});s=x.state;
assert.equal(e(x.view,'2').primary.ffDigital.value,10);
x=go(s,'ADVANCE_SECONDS',{value:10});s=x.state;
assert.equal(e(x.view,'2').primary.ffDigital.mode,'FLOW');
x=go(s,'SET_INSTRUMENT_SIGNAL',{engine:2,instrument:'fuelFlowKgHr',value:'SIGNAL_LOSS'});s=x.state;
x=go(s,'ADVANCE_SECONDS',{value:2});s=x.state;
assert.equal(e(x.view,'2').fuelUsedKg,null);
assert.equal(e(x.view,'2').primary.fuelFlowKgHr.display,'DASHES');
assert.throws(()=>go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'oilQtyPct',value:110}),TypeError);
assert.throws(()=>go(s,'SET_ENGINE_INDICATION',{engine:1,instrument:'typo',value:12}),TypeError);
