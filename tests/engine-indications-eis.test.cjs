'use strict';
const assert=require('node:assert/strict');
const {initialAircraftState:init,transitionAircraftState:step,replayAircraftActions:replay}=require('../engine/network/integrated-aircraft-kernel.cjs');
const go=(s,type,data={})=>step(s,{type,...data});
const start=init();
assert.deepEqual(replay(start,[]).view.indications.engines,{});
let x=go(start,'ENTER_COLD_DARK'),s=x.state;
const e=(v,i='1')=>v.indications.engines[i];
assert.equal(e(x.view).primary.n1Pct.display,'NO_DATA');
