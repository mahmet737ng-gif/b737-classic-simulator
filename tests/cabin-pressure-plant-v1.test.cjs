'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const plant=require('../engine/systems/cabin-pressure-plant-v1');
const profile=require('../engine/config/aircraft-profile-v1');
const cpcs=require('../engine/systems/cpcs-v5');
const dcpcs=require('../engine/systems/dcpcs-v4');
function integrate(s,options,duration=20000){for(let t=0;t<duration;t+=1000)s=plant.step(s,{...options,ms:1000});return s;}
const base=plant.initial();
assert.ok(Math.abs(plant.observe(base).cabinAltitudeFt)<0.001);
const noPack=integrate(base,{aircraftAltitudeFt:0,onGround:true,packsAvailable:false,outflowCommand:'DRIVE_FULL_OPEN'});
assert.ok(Math.abs(plant.observe(noPack).differentialPsid)<0.001,'No supplied air must not inflate cabin');
const pressurized=integrate(base,{aircraftAltitudeFt:0,onGround:true,packsAvailable:true,mode:'MAN',outflowCommand:'CLOSE'},40000);
const venting=integrate(base,{aircraftAltitudeFt:0,onGround:true,packsAvailable:true,mode:'MAN',outflowCommand:'OPEN'},40000);
assert.ok(pressurized.valveOpenFraction<0.001,'Manual valve must reach closed');
assert.ok(venting.valveOpenFraction>.999,'Manual valve must reach open');
assert.ok(plant.observe(pressurized).differentialPsid>plant.observe(venting).differentialPsid,'Valve must change air pressure');
assert.ok(plant.observe(pressurized).differentialPsid<=plant.PARAMETERS.positiveReliefPsid+0.0001,'Mechanical relief must limit pressure');
const climb=integrate(base,{aircraftAltitudeFt:28000,onGround:false,packsAvailable:true,mode:'AUTO',outflowCommand:'AUTO_RATE_CONTROL_NO_NUMERIC_SCHEDULE'},60000);
const c=plant.observe(climb);
assert.ok(Number.isFinite(c.cabinAltitudeFt)&&Number.isFinite(c.cabinRateFtMin)&&Number.isFinite(c.differentialPsid));
assert.ok(c.valveOpenFraction>=0&&c.valveOpenFraction<=1);
const engines={B737CPCSV5:cpcs,B737DCPCSV4:dcpcs,B737CabinPressurePlantV1:plant};
const a=profile.createPressurizationSession({...profile.DEFAULTS,pressurization:'CPCS'},engines);
const b=profile.createPressurizationSession({...profile.DEFAULTS,pressurization:'DCPCS'},engines);
assert.equal(a.physical().status,'PROVISIONAL_TRAINING_PHYSICS_NOT_AIRCRAFT_VALIDATED');
assert.equal(b.physical().status,'PROVISIONAL_TRAINING_PHYSICS_NOT_AIRCRAFT_VALIDATED');
a.dispatch({type:'MODE',value:'MAN_DC'});
b.dispatch({type:'MODE',value:'MAN'});
a.dispatch({type:'VALVE_SWITCH',value:'CLOSE'});
b.dispatch({type:'MANUAL_SWITCH',value:'OPEN'});
for(let n=0;n<25;n++){
 a.stepPhysics(1000,{aircraftAltitudeFt:0,onGround:true,packsAvailable:true});
 b.stepPhysics(1000,{aircraftAltitudeFt:0,onGround:true,packsAvailable:true});
}
assert.equal(a.read().operatingMode,'MAN_DC');
assert.equal(b.read().operatingMode,'MAN');
assert.equal(a.snapshot().selectedMode,'MAN_DC');
assert.equal(b.snapshot().selector,'MAN');
assert.ok(a.physical().differentialPsid>b.physical().differentialPsid);
assert.equal(a.snapshot().inputs.cabinAltitudeFt,a.physical().cabinAltitudeFt);
assert.equal(b.snapshot().input.cabinDifferentialPsid,b.physical().differentialPsid);
assert.equal(a.snapshot().inputs.cabinRateFtMin,a.physical().cabinRateFtMin);
assert.equal(b.snapshot().input.cabinRateFtMin,b.physical().cabinRateFtMin);
assert.throws(()=>a.stepPhysics(-1),/Invalid pressure integration period/);
assert.throws(()=>b.stepPhysics(1000,{aircraftAltitudeFt:100000}),/outside trainer envelope/);
assert.equal(a.snapshot().selectedMode,'MAN_DC','Failed physical tick must not corrupt controller');
a.reset();assert.equal(a.read().selectedMode,'AUTO');
assert.equal(b.read().selectedMode,'MAN','Reset of CPCS must not reset DCPCS');
const plain=profile.createPressurizationSession(profile.DEFAULTS,{B737CPCSV5:cpcs,B737DCPCSV4:dcpcs});
assert.equal(plain.physical(),null,'Old controller-only integrations must remain intact');
const html=fs.readFileSync(path.join(__dirname,'../panel-mosaic-lab/cockpit/index.html'),'utf8');
assert.ok(html.includes('cabin-pressure-plant-v1.js'),'Unified must load training plant');
const runtime=fs.readFileSync(path.join(__dirname,'../panel-mosaic-lab/cockpit/aircraft-settings.js'),'utf8');
assert.ok(runtime.includes('session.stepPhysics(1000,'),'Unified must advance physical time');
assert.ok(runtime.includes('publishPressureState(active)'),'Unified must publish pressure state to OH22');
assert.ok(runtime.includes('PRESSURE PHYSICS STOPPED'),'Faulty physics must surface diagnostic');
console.log('PASS: CPCS/DCPCS isolated pressure feedback, reversible outflow, pack dependency, relief, diagnostics and fault containment.');
