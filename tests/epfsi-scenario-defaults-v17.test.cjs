'use strict';
const assert=require('node:assert/strict');
const env=require('../engine/fmc/performance/epfsi-scenario-defaults-v17.cjs');
const cdu=require('../engine/fmc/performance/afm-epfsi-n1-v10.cjs');
const pmc=require('../engine/fmc/performance/afm-epfsi-pmc-off-v16.cjs');
let count=0;function test(name,fn){fn();++count;console.log('PASS',name);}
const eq=(a,b)=>assert.equal(a,b);
test('ISA at sea level 15C',()=>eq(env.isaOatC(0),15));
test('ISA at 10000 ft ~ minus 4.8 C',()=>assert.ok(Math.abs(env.isaOatC(10000)-(-4.812))<0.002));
test('ISA tropopause -56.5C',()=>assert.ok(Math.abs(env.isaOatC(11000/0.3048)+56.5)<.00001));
test('ISA above tropopause isothermal',()=>eq(env.isaOatC(40000),-56.5));
test('no altitude does not invent sea-level OAT',()=>eq(env.isaOatC(null),null));
test('default weather mode ISA',()=>eq(env.normalize({}).weatherMode,'ISA'));
test('default anti ice OFF',()=>eq(env.normalize({}).antiIceMode,'OFF'));
test('default engine bleed ON',()=>eq(env.normalize({}).engineBleedMode,'ON'));
test('default A/C packs AUTO distinct from bleed ON',()=>eq(env.normalize({}).acPacks,'AUTO'));
test('default bleedMode ON for CDU',()=>eq(env.normalize({}).bleedMode,'ON'));
test('PMC still UNKNOWN',()=>eq(env.normalize({}).pmcMode,'UNKNOWN'));
test('temperature derived by pressure altitude',()=>assert.ok(Math.abs(env.normalize({pressureAltitudeFt:5000}).oatC-5.094)<0.002));
test('weather override OAT implies custom mode',()=>{const v=env.normalize({pressureAltitudeFt:5000,oatC:32});eq(v.weatherMode,'CUSTOM');eq(v.oatC,32)});
test('explicit ISA wins over stale manual OAT',()=>assert.ok(Math.abs(env.normalize({weatherMode:'ISA',pressureAltitudeFt:5000,oatC:32}).oatC-5.094)<0.002));
test('explicit anti-ice override honored',()=>eq(env.normalize({antiIceMode:'ENGINE'}).antiIceMode,'ENGINE'));
test('explicit bleed OFF override honored',()=>eq(env.normalize({engineBleedMode:'OFF'}).engineBleedMode,'OFF'));
test('pack-specific override honored',()=>eq(env.normalize({acPacks:'HIGH'}).acPacks,'HIGH'));
test('no fabricated TAT under ISA',()=>eq(env.normalize({pressureAltitudeFt:12000,mach:0.6}).tatC,null));
test('explicit TAT preserved',()=>eq(env.normalize({tatC:-9}).tatC,-9));
test('PMC explicit state preserved',()=>eq(env.normalize({pmcMode:'OFF'}).pmcMode,'OFF'));
test('CDU baseline still blocks incomplete curves',()=>eq(cdu.cduAdapter({...env.normalize({pressureAltitudeFt:5000}),phase:'TAKEOFF',iasKts:50,pmcMode:'NORMAL'}).display,'---.-'));
test('PMC OFF baseline source selected 756 with defaults',()=>eq(cdu.chartFor({...env.normalize({pressureAltitudeFt:5000}),phase:'TAKEOFF',pmcMode:'OFF'}).chart.pdfPage,756));
test('PMC OFF v16 validates normalized engine bleed and packs',()=>assert.doesNotThrow(()=>pmc.gate({...env.normalize({pressureAltitudeFt:5000}),phase:'TAKEOFF',pmcMode:'OFF',iasKts:50})));
test('PMC OFF v16 no source means no N1',()=>eq(pmc.calculate({...env.normalize({pressureAltitudeFt:5000}),phase:'TAKEOFF',pmcMode:'OFF',iasKts:50},null).n1Pct,null));
test('bad anti ice rejected',()=>assert.throws(()=>env.normalize({antiIceMode:'WHAT'}),/INVALID_ANTI_ICE/));
console.log('PASS '+count+' EP-FSI ISA / anti-ice OFF / bleed ON simulator default cases');