const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const core=require('../engine/mechanics/compound-controls.js');
const catalog=JSON.parse(fs.readFileSync(path.join(__dirname,'../engine/atlas/compound-controls.v1.json'),'utf8'));
assert.deepEqual(core.validate(catalog),[]);
let s=core.makeState(catalog);
assert.equal(Object.keys(s).length,4);
const IRS_BRT='overhead.irs.isdu.brightness.inner';
const IRS_OUT='overhead.irs.isdu.display_selector.outer';
const HDG='main.mcp.heading.inner';
const BANK='main.mcp.bank_angle.outer';
assert.equal(core.hitTest(catalog,'overhead',800,616),IRS_BRT);
assert.equal(core.hitTest(catalog,'overhead',800+44,616),IRS_OUT);
assert.equal(core.hitTest(catalog,'overhead',800+52,616),null);
assert.equal(core.hitTest(catalog,'main',3062,270),HDG);
assert.equal(core.hitTest(catalog,'main',3062+58,270),BANK);
let r=core.apply(catalog,s,IRS_OUT,'SET','WIND');assert.equal(r.ok,true); s=r.state;
assert.equal(s[IRS_BRT],0.75);assert.equal(s[IRS_OUT],'WIND');
r=core.apply(catalog,s,IRS_BRT,'STEP',-1);s=r.state;
assert.equal(s[IRS_BRT],0.7);assert.equal(s[IRS_OUT],'WIND');
r=core.apply(catalog,s,IRS_OUT,'SET','TEST'); s=r.state;assert.equal(s[IRS_OUT],'TEST');
r=core.apply(catalog,s,IRS_OUT,'RELEASE');s=r.state;assert.equal(s[IRS_OUT],'TK/GS');
r=core.apply(catalog,s,IRS_OUT,'SET','ATT');assert.equal(r.ok,false);
r=core.apply(catalog,s,HDG,'SET',359);s=r.state;
r=core.apply(catalog,s,HDG,'STEP',1);s=r.state;assert.equal(s[HDG],0);
r=core.apply(catalog,s,HDG,'STEP',-1);s=r.state;assert.equal(s[HDG],359);
r=core.apply(catalog,s,BANK,'SET',15);s=r.state;assert.equal(s[HDG],359);
r=core.apply(catalog,s,BANK,'STEP',-1);s=r.state;assert.equal(s[BANK],10);
r=core.apply(catalog,s,BANK,'STEP',-1);s=r.state;assert.equal(s[BANK],10);
r=core.apply(catalog,s,BANK,'SET',13);assert.equal(r.ok,false);
r=core.apply(catalog,s,HDG,'STEP',NaN);assert.equal(r.ok,false);
r=core.apply(catalog,s,'not-a-control','STEP',1);assert.equal(r.ok,false);
assert.notEqual(s,core.makeState(catalog));
console.log('PASS 23 assertions: 2 nested groups, 4 independent controls, geometry, detents, wrap, spring return, failure paths');