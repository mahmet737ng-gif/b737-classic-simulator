'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const base=path.resolve(__dirname,'..');
const ehsi=require('../cdu-standalone-v6/ehsi/ehsi-engine.js');
assert.equal(ehsi.defaultModel().efis.dh,200,'DH reference starts at 200');
const st={ehsi:ehsi.defaultModel()};
for(let i=0;i<250;i++)ehsi.step(st,'dh',-1);
assert.equal(st.ehsi.efis.dh,-20,'DH clamps at -20');
for(let i=0;i<1100;i++)ehsi.step(st,'dh',1);
assert.equal(st.ehsi.efis.dh,999,'DH clamps at 999');
ehsi.modelFor(st).efis.dh=200;
ehsi.step(st,'dh',1);
assert.equal(st.ehsi.efis.dh,201,'DH turns one unit per detent');
const win={EHSI_ENGINE:ehsi};
vm.runInNewContext(fs.readFileSync(path.join(base,'cdu-standalone-v6/ehsi/photo-panel.js'),'utf8'),{window:win,localStorage:{getItem(){return null}}});
assert.equal(win.EHSI_ENGINE.photo.dhRange.min,-20);
assert.equal(win.EHSI_ENGINE.photo.dhRange.max,999);
assert.equal(win.EHSI_ENGINE.photo.geometry.wxr.title,'WXR pushbutton');
assert.equal(Object.keys(win.EHSI_ENGINE.photo.geometry).length,13);
const photo=win.EHSI_ENGINE.photo;
assert.deepEqual(Array.from(photo.modeClockwise),['EXP_NAV','EXP_VOR_ILS','MAP','CTR_MAP','PLAN','FULL_NAV','FULL_VOR_ILS']);
assert.deepEqual(Object.keys(photo.rangeAngle).map(Number),[10,20,40,80,160,320]);
st.ehsi.mode='MAP';photo.rotate(st,'mode',1);assert.equal(st.ehsi.mode,'CTR_MAP');
photo.rotate(st,'mode',1);assert.equal(st.ehsi.mode,'PLAN');
photo.rotate(st,'mode',1);assert.equal(st.ehsi.mode,'FULL_NAV');
st.ehsi.range=10;photo.rotate(st,'range',-1);assert.equal(st.ehsi.range,10,'end stop no wrap');
photo.rotate(st,'range',1);assert.equal(st.ehsi.range,20);
st.ehsi.efis.dh=-20;photo.rotate(st,'dh',-1);assert.equal(st.ehsi.efis.dh,-20);
photo.rotate(st,'dh',1);assert.equal(st.ehsi.efis.dh,-19);
const html=fs.readFileSync(path.join(base,'cdu-standalone-v6/index.html'),'utf8');
assert.match(html,/ehsi\/photo-panel\.js/);
assert.match(html,/ehsi\/photo-panel\.css/);
assert.match(html,/cdu-approved-unlit\.png/);
console.log('EFIS photo overlay state and integration contracts: PASS');
