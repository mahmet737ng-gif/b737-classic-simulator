'use strict';
const assert=require('node:assert/strict');
const ECU=require('../engine/integration/isn-13-18-ecu-testbench-v1');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const Chain=require('../engine/integration/isn-apu-start-chain-v1');
const ThrustPlanner=require('../engine/integration/isn-thrust-performance-v1');
const FuelRuntime=require('../engine/integration/isn-09-12-runtime-v1');
const rig=()=>new ECU.Testbench({Electrical,Loads,TrainerCore,WarningEngine,
 Pneumatics,Pack,EngineAPU,Start,Chain,ThrustPlanner,FuelRuntime,timingProfile:'CLASSROOM_COMPRESSED'});
const a=rig();
assert.equal(a.get().engineStartBackend.engine1.status,'STOPPED');
assert.equal(a.get().engineStartBackend.engine1.prestart.ductPressureMeasured,false);
a.setStartDuctPressure('engine1',25);
assert.equal(a.get().engineStartBackend.engine1.prestart.ductBelowGuide,true);
a.battery(true);a.startAPU();a.advance(1400);a.apuBleed(true);
a.setStandbyPower('BAT');a.setIgnitionSelector('IGN_R');a.engineStart('engine1');
assert.equal(a.get().engineStartBackend.engine1.status,'DRY_MOTORING');
assert.equal(a.get().engineStartBackend.engine1.lamps.startValveOpen,true);
a.advance(Math.round(850*35/25));
assert.equal(a.get().engineStartBackend.engine1.status,'FUEL_INTRODUCTION_CUE');
a.fuelLever('engine1','IDLE');
assert.equal(a.get().engineStartBackend.engine1.ignition.eligible.right,true);
a.advance(Math.round(1000*35/25));
let z=a.get().engineStartBackend.engine1;
assert.equal(z.phase,'RUNNING');
assert.equal(z.starter.released,true);
assert.equal(z.starter.autoCutoutAt46N2,true);
assert.equal(z.groundIdleStabilized,false);
a.advance(11000);z=a.get().engineStartBackend.engine1;
assert.equal(z.status,'STABILIZED_GROUND_IDLE');
assert.equal(z.lamps.oilLowPressure,false);
assert.equal(a.get().engineStartBackend.engine2.status,'STOPPED');
const b=rig();b.battery(true);b.startAPU();b.advance(1400);b.selectGenerator('APU',1);b.apuBleed(true);
b.engineStart('engine2');b.advance(120000);b.advance(10);
z=b.get().engineStartBackend.engine2;
assert.equal(z.status,'STARTER_TIME_LIMIT');
assert.equal(z.starter.engagedObserved,false);
assert.equal(z.starter.valveOpenObserved,false);
assert.equal(z.starter.maxUseSec,120);
console.log('PASS CLASSIC ENGINE START BACKEND');
// Real-time regression: N2 stays moving until the same update releases GRD.
const continuous=new ECU.Testbench({Electrical,Loads,TrainerCore,WarningEngine,
 Pneumatics,Pack,EngineAPU,Start,Chain,ThrustPlanner,FuelRuntime,timingProfile:'REALTIME_TRAINING'});
continuous.battery(true);continuous.startAPU();continuous.advance(85000);continuous.apuBleed(true);
continuous.setStandbyPower('BAT');continuous.setIgnitionSelector('IGN_R');continuous.prepareFuel();
continuous.engineStart('engine1');continuous.advance(28000);continuous.fuelLever('engine1','IDLE');
const remaining=continuous.chain.startDuration('engine1').lightoffMs;
continuous.advance(remaining-1000);
const n2a=continuous.get().engines.engine1.n2Percent;
continuous.advance(500);
const n2b=continuous.get().engines.engine1.n2Percent;
assert.ok(n2b-n2a>.2,'N2 must not flatten in the final second');
continuous.advance(499);
assert.ok(continuous.chain.get().observations.engine1.feedback.n2Percent.value<46);
assert.equal(continuous.get().engineStartBackend.engine1.controls.startSwitch,'GRD');
continuous.chain.consumeEffects();continuous.advance(1);
const crossed=continuous.get().engineStartBackend.engine1;
assert.equal(crossed.controls.startSwitch,'OFF');
assert.equal(crossed.starter.valveOpenObserved,false);
assert.equal(crossed.phase,'RUNNING');
assert.equal(continuous.chain.consumeEffects().filter(e=>e.type==='ROTARY_RELEASE'&&e.id==='engine-start-1').length,1);
continuous.advance(100);
assert.ok(continuous.get().engines.engine1.n2Percent>46,'N2 continues after cutout');
assert.equal(continuous.get().engineStartBackend.engine2.status,'STOPPED');
console.log('PASS real-time N2 crossing and starter release share one update, with no N2 plateau.');
