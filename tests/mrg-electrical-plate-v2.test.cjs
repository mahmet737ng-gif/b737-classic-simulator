'use strict';
// MRG visual-regression contract: presentation preserves source proportions;
// relay/source selectors are intentionally removed from the user-facing lab.
const assert=require('node:assert/strict');
const test=require('node:test');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const Lab=require('../engine/systems/classic-bus-consumer-test-lab-v1.js');
const Plate=require('../bus-consumer-test-lab/mrg-electrical-plate-v2.js');
const Core=require('../engine/systems/classic-bus-consumer-engine-v1.js');
const Electrical=require('../engine/systems/electrical-v7.js');
const index=require('../engine/systems/mrg-classic-340-consumer-bus-index-v1.json');
const html=read('bus-consumer-test-lab/v3.html');
const js=read('bus-consumer-test-lab/mrg-electrical-plate-v2.js');
const css=read('bus-consumer-test-lab/mrg-electrical-plate-v2.css');
const keys=Object.keys(Lab.SOURCE);
const reference=Object.fromEntries(keys.map(id=>[id,{powered:true}]));
const state=cuts=>Lab.calculatePower(reference,cuts,'ALL_ON',true);
test('24 bus classes and original-aspect SVG with no anisotropic stretch',()=>{
 assert.equal(keys.length,24);
 assert.equal(Object.keys(Plate.BUS).length,24);
 assert.match(Plate.VERSION,/0005$/);
 assert.match(js,/viewBox:'0 100 616 708'/);
 assert.match(js,/preserveAspectRatio:'xMidYMid meet'/);
 assert.doesNotMatch(js,/scale\(1\.80 0\.955\)/);
 assert.doesNotMatch(js,/preserveAspectRatio:'none'/);
 assert.match(css,/MRG COMPOSED LAYOUT V4/);
 assert.match(css,/\.mrg-quick-panel/);
 assert.match(css,/\.mrg-sheet-holder svg/);
 assert.match(css,/MRG REFERENCE FRAME V5/);
 assert.match(css,/aspect-ratio:4 \/ 3!important/);
 assert.match(css,/overflow-y:auto!important/);
 assert.match(css,/aspect-ratio:616 \/ 708!important/);
 assert.match(css,/align-self:start!important/);
 assert.match(html,/MRG-REF-4X3-V5-0001/);
});
test('Relay/source controls are not loaded or interactive',()=>{
 assert.doesNotMatch(html,/mrg-electrical-controls-v3\.js/);
 assert.doesNotMatch(js,/B737MRGContactNetworkV3/);
 assert.doesNotMatch(js,/function toggleRelay\(/);
 assert.doesNotMatch(js,/function toggleSource\(/);
 assert.doesNotMatch(js,/setPowerModel\(/);
 assert.doesNotMatch(js,/function updateContacts\(/);
 assert.doesNotMatch(js,/transform:'translate\(-122 -102\) scale/);
 assert.doesNotMatch(js,/text\(parent,308,55,'ELECTRICAL POWER SCHEMATIC'/);
 assert.match(js,/'data-closed':'unverified'/);
});
test('Visual state still distinguishes a direct cut, cascade, and alternate feed',()=>{
 const all=state([]);
 assert.equal(Object.values(all).filter(Boolean).length,24);
 assert.equal(Plate.classifyWire({bus:'generator1@115VAC'},all,new Set()),'ON');
 const cuts=new Set(['generator1@115VAC']);
 const p=state([...cuts]);
 assert.equal(p['generator1@115VAC'],false);
 assert.equal(p['main1@115VAC'],false);
 assert.equal(p['main1@28VAC'],false);
 assert.equal(p['transfer1@115VAC'],true,'second generator supplies alternate transfer feed');
 assert.equal(Plate.classifyWire({bus:'generator1@115VAC'},p,cuts),'DIRECT');
 assert.equal(Plate.classifyWire({bus:'main1@28VAC'},p,cuts),'CASCADE');
 assert.equal(Plate.classifyWire({bus:'transfer1@115VAC',from:'generator2@115VAC'},p,cuts),'ON');
 assert.match(css,/mrg-wire\[data-power="ON"\]/);
 assert.match(css,/mrg-wire\[data-power="OFF"\]/);
 assert.match(css,/mrg-wire\[data-failure-type="CASCADE"\]/);
});
test('Existing test lab still projects real bus cuts into 340 source rows',()=>{
 const session=Lab.makeSession({Core,Electrical,index});
 session.setCascade(true);
 assert.equal(session.snapshot().coverage.activeRows,340);
 session.set('generator1@115VAC',false);
 assert.equal(session.busStates['main1@115VAC'],false);
 assert.equal(session.busStates['generator2@115VAC'],true);
 assert.ok(Object.values(session.snapshot().consumers).some(entry=>entry.powerState==='OFF'));
 session.restore();
 assert.equal(session.snapshot().coverage.activeRows,340);
 assert.equal(Object.values(session.busStates).filter(Boolean).length,24);
});
