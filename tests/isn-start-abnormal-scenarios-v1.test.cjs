'use strict';
const assert=require('node:assert/strict');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const {Chain}=require('../engine/integration/isn-apu-start-chain-v1');
const fs=require('node:fs');
const path=require('node:path');
function prepared(){const session=new Start.Session({EngineAPU,ElectricalPack:Pack,Electrical,Loads,TrainerCore,WarningEngine,Pneumatics});
 const chain=new Chain(session);
 chain.synchronize({toggles:{'bleed-apu':'ON','pack-l':'OFF','pack-r':'OFF','isolation-valve':'OPEN'},
  guards:{'battery-master':{value:'on'}},rotaries:{'ignition-source':'BOTH'},context:{onGround:true}});
 chain.event({id:'apu-start',kind:'toggle',next:'START'});chain.advance(1400);
 session.core.pack.send({type:'ELECTRICAL',action:{type:'SELECT_SOURCE',source:'APU',side:1}});
 chain.syncPower();return chain;
}
let chain=prepared();
chain.setTrainingFault('engine1','n2Stall',true);
assert.equal(chain.get().trainingFaults.engine1.n2Stall,true);
chain.event({id:'engine-start-1',kind:'rotary',next:'GRD'});
assert.throws(()=>chain.setTrainingFault('engine1','n2Stall',false),/before ENGINE START GRD/);
chain.advance(850);
let s=chain.get();
assert.equal(s.phase.engine1,'N2_STALLED');
assert.equal(s.observations.engine1.feedback.n2Percent.value,18);
assert.equal(s.sources.engine1.running,false);
assert.equal(s.projected.mainStartValve1,true);
chain.lever('engine1','IDLE');
assert.equal(chain.get().observations.engine1.feedback.fuelStartLever.value,'CUTOFF');
chain.lever('engine1','CUTOFF');s=chain.get();
assert.equal(s.phase.engine1,'OFF');
assert.equal(s.projected.mainStartValve1,false);
assert.equal(s.observations.engine1.feedback.n2Percent.value,null);
chain.advance(5000);assert.equal(chain.get().sources.engine1.running,false);

chain=prepared();chain.setTrainingFault('engine2','egtHigh',true);
chain.event({id:'engine-start-2',kind:'rotary',next:'GRD'});chain.advance(850);
chain.lever('engine2','IDLE');chain.advance(950);s=chain.get();
assert.equal(s.phase.engine2,'ABNORMAL_EGT');
assert.ok(s.observations.engine2.feedback.egtC.value>=725);
assert.equal(s.observations.engine2.rules.advisory.egt725Latched,true);
assert.equal(s.sources.engine2.running,false);
assert.equal(s.projected.mainStartValve2,true,'the training model does not claim an automatic valve closure');
chain.advance(5000);assert.equal(chain.get().sources.engine2.running,false);
chain.lever('engine2','CUTOFF');s=chain.get();
assert.equal(s.phase.engine2,'OFF');
assert.equal(s.observations.engine2.feedback.fuelFlowKgHr.value,0);
assert.equal(s.observations.engine2.rules.advisory.egt725Latched,false);
assert.equal(s.projected.mainStartValve2,false);
const ui=fs.readFileSync(path.join(__dirname,'../panel-mosaic-lab/cockpit/isn-cockpit.js'),'utf8');
assert.match(ui,/data-start-fault="engine1:n2Stall"/);
assert.match(ui,/data-start-fault="engine2:egtHigh"/);
console.log('PASS ISN-06 instructor N2-stall and high-EGT scenarios; source-backed EGT advisory and manual cutoff remain separate.');
