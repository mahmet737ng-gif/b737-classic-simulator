'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const Core=require('../engine/systems/hydraulic-test-lab-core-v1.js');
const repo=path.join(__dirname,'../panel-mosaic-lab/cockpit');
const read=p=>fs.readFileSync(path.join(repo,p),'utf8');
const run=(p,seconds)=>Core.evaluate(Core.step(Core.loadPreset(p),seconds));
test('B737 classic ATA29 pump crossfeed is ENG1 + ELEC2 for A, ENG2 + ELEC1 for B',()=>{
 assert.equal(Core.PUMP['hyd-eng-1'].system,'A');
 assert.equal(Core.PUMP['hyd-elec-2'].system,'A');
 assert.equal(Core.PUMP['hyd-elec-1'].system,'B');
 assert.equal(Core.PUMP['hyd-eng-2'].system,'B');
 const healthy=Core.evaluate(Core.loadPreset('healthy'));
 assert.deepEqual(healthy.pressurePsi,{A:3000,B:3000,STBY:0,BRAKE:3000});
 assert.deepEqual(healthy.quantityPct,{A:100,B:100,STBY:100});
 assert.equal(healthy.lamps['hyd-eng-1'],false);
 assert.equal(healthy.lamps['hyd-elec-2'],false);
 assert.equal(healthy.alerts.sixPackHyd,false);
});
test('Normal scenarios are numerically stable and pressure sources independent',()=>{
 const cold=run('cold',10);assert.equal(cold.pressurePsi.A,0);assert.equal(cold.pressurePsi.B,0);
 assert.equal(cold.alerts.masterCaution,false);
 assert.ok(Object.values(cold.lamps).every(v=>v===false));
 const a=run('eng1',10),b=run('eng2',10),electrics=run('electric',10),push=run('pushback',10);
 assert.ok(a.pressurePsi.A>=2900&&a.pressurePsi.B<100);
 assert.ok(b.pressurePsi.A<100&&b.pressurePsi.B>=2900);
 assert.ok(electrics.pressurePsi.A>=2900&&electrics.pressurePsi.B>=2900);
 assert.ok(push.pressurePsi.A<100&&push.pressurePsi.B>=2900);
 assert.ok(electrics.lamps['hyd-eng-1'],'Unavailable engine pump shows LOW PRESS');
 assert.ok(!electrics.lamps['hyd-elec-2'],'Available ELEC 2 motor clears LOW PRESS');
});
test('Independent electric motor failures do not remove surviving system engine pump pressure',()=>{
 let s=Core.loadPreset('healthy');
 s=Core.command(s,{type:'INJECT',id:'ELEC2_PUMP_FAIL'});
 let out=Core.evaluate(s);
 assert.equal(out.pumps['hyd-elec-2'].active,false);
 assert.equal(out.lamps['hyd-elec-2'],true);
 assert.equal(out.pressurePsi.A,3000,'engine1 retains normal A pressure');
 assert.equal(out.pressurePsi.B,3000,'B never depends on ELEC2');
 s=Core.command(s,{type:'INJECT',id:'ENG1_PUMP_FAIL'});
 s=Core.step(s,20);out=Core.evaluate(s);
 assert.ok(out.pressurePsi.A<200,'A loses both supplying pumps');
 assert.equal(out.pressurePsi.B,3000);
 assert.ok(out.alerts.sixPackHyd);
 s=Core.command(s,{type:'CLEAR',id:'ELEC2_PUMP_FAIL'});
 s=Core.step(s,14);out=Core.evaluate(s);
 assert.ok(out.pressurePsi.A>2900,'restoring ELEC2 recovers System A');
});
test('Standalone bus-loss and FIRE switch cannot invent pump supply',()=>{
 let s=Core.loadPreset('electric');
 s=Core.command(s,{type:'INJECT',id:'AC2_BUS_LOST'});
 s=Core.step(s,20);let out=Core.evaluate(s);
 assert.ok(out.pressurePsi.A<200&&out.pressurePsi.B>2900);
 s=Core.loadPreset('healthy');
 s=Core.command(s,{type:'SET_ENV',id:'fireHandle1',value:true});
 out=Core.evaluate(s);
 assert.equal(out.pumps['hyd-eng-1'].blocked,true);
 assert.equal(out.pumps['hyd-eng-1'].fireLampInhibited,true);
 assert.equal(out.lamps['hyd-eng-1'],false,'FCOM pulled fire switch inhibits EDP LOW PRESS lens');
});
test('Pressure response is smooth and never exceeds gauge scale 0..4000',()=>{
 let s=Core.loadPreset('electric');
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-elec-2',value:'OFF'});
 const previous=s.pressure.A;s=Core.step(s,.5);
 assert.ok(s.pressure.A<previous&&s.pressure.A>0,'pressure falls continuously, not instantly');
 s=Core.step(s,30);
 assert.ok(s.pressure.A<2);
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-elec-2',value:'ON'});
 s=Core.step(s,.5);
 assert.ok(s.pressure.A>0&&s.pressure.A<3000,'pressure recovers smoothly');
 s=Core.step(s,20);
 assert.ok(s.pressure.A>2990&&s.pressure.A<=3500);
});
test('Large hydraulic leaks change reservoir quantity and own-system pressure',()=>{
 const a=run('a-lost',40),b=run('b-lost',40),both=run('dual-lost',40);
 assert.ok(a.pressurePsi.A<50&&a.pressurePsi.B>=2900);
 assert.equal(a.quantityPct.A,0);assert.equal(a.quantityPct.B,100);
 assert.ok(b.pressurePsi.B<50&&b.pressurePsi.A>=2900);
 assert.equal(b.quantityPct.B,0);
 assert.ok(both.pressurePsi.A<50&&both.pressurePsi.B<50);
 assert.ok(both.quantityPct.A===0&&both.quantityPct.B===0);
});
test('Sensor, lamp and power failure classes remain distinct from physical pressure',()=>{
 let s=Core.loadPreset('healthy');
 s=Core.command(s,{type:'INJECT',id:'A_PRESS_SENSOR_OPEN'});
 s=Core.command(s,{type:'INJECT',id:'A_QTY_SENSOR_FAIL'});
 let out=Core.evaluate(s);
 assert.equal(out.indications['eng.hyd_pressure.a'],null);
 assert.equal(out.indications['eng.hyd_qty.a'],null);
 assert.equal(out.pressurePsi.A,3000,'sensor fail does not fabricate hydraulic pressure loss');
 s=Core.command(s,{type:'INJECT',id:'ELEC2_PUMP_FAIL'});
 s=Core.command(s,{type:'INJECT',id:'ELEC2_LOW_LAMP_FAIL'});
 out=Core.evaluate(s);
 assert.equal(out.pumps['hyd-elec-2'].lowPressure,true);
 assert.equal(out.lamps['hyd-elec-2'],false,'lamp failure hides existing pump fault');
 s=Core.command(s,{type:'INJECT',id:'ELEC1_OVHT'});
 out=Core.evaluate(s);
 assert.equal(out.lamps['hyd-elec-1-overheat'],true);
 s=Core.command(s,{type:'INJECT',id:'ELEC1_OVHT_LAMP_FAIL'});
 assert.equal(Core.evaluate(s).lamps['hyd-elec-1-overheat'],false);
});
test('Brake accumulator is a separate indication; pressure retained without B and decreases on use',()=>{
 let s=Core.loadPreset('healthy');
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-eng-2',value:'OFF'});
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-elec-1',value:'OFF'});
 s=Core.step(s,20);
 let out=Core.evaluate(s);
 assert.ok(out.pressurePsi.B<100);
 assert.ok(out.pressurePsi.BRAKE>2700);
 // System A still supplies alternate brakes. Stored accumulator pressure
 // is used only after BOTH normal B and alternate A are unavailable.
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-eng-1',value:'OFF'});
 s=Core.command(s,{type:'SET_SWITCH',id:'hyd-elec-2',value:'OFF'});
 s=Core.step(s,20);
 out=Core.evaluate(s);
 assert.ok(out.pressurePsi.A<100&&out.pressurePsi.B<100);
 const before=out.pressurePsi.BRAKE;
 s=Core.command(s,{type:'BRAKE',count:2});
 out=Core.evaluate(s);
 assert.ok(out.pressurePsi.BRAKE<before,'two brake presses use stored accumulator');
 assert.equal(out.indications['fo.hyd_brake_pressure'],out.pressurePsi.BRAKE);
 const depleted=run('brake-accum',35);
 assert.ok(depleted.pressurePsi.BRAKE<100);
});
test('Standby only pressurizes on command; engine systems remain hydraulically separate',()=>{
 const s=run('standby',10);
 assert.ok(s.pressurePsi.STBY>2800&&s.pressurePsi.A>=2900&&s.pressurePsi.B>=2900);
 assert.equal(s.lamps['stby-rudder'],true);
 let f=Core.loadPreset('standby');
 f=Core.command(f,{type:'INJECT',id:'STBY_PUMP_FAIL'});
 f=Core.step(f,30);
 const out=Core.evaluate(f);
 assert.ok(out.pressurePsi.STBY<100);
 assert.equal(out.lamps['stby-pressure'],true);
 assert.ok(out.pressurePsi.A>2900&&out.pressurePsi.B>2900);
});
test('All explicit failure presets and mixed faults are selectable without duplicate IDs',()=>{
 const presets=new Set(Core.PRESETS.map(x=>x.id)),faults=new Set(Core.FAULTS.map(x=>x.id));
 assert.ok(Core.PRESETS.length>=15);
 assert.ok(Core.FAULTS.length>=60);
 assert.equal(presets.size,Core.PRESETS.length);
 assert.equal(faults.size,Core.FAULTS.length);
 const groups=new Set(Core.FAULTS.map(x=>x.category));
 for(const c of ['PUMPS','POWER','SYSTEM','STANDBY','BRAKES','FLIGHT_CONTROLS','SENSORS','WARNINGS'])assert.ok(groups.has(c));
 let s=Core.loadPreset('healthy');
 for(const id of faults)s=Core.command(s,{type:'INJECT',id});
 assert.equal(s.faults.length,Core.FAULTS.length);
 s=Core.command(s,{type:'CLEAR',id:'A_PRESS_SENSOR_OPEN'});
 assert.equal(s.faults.length,Core.FAULTS.length-1);
 s=Core.command(s,{type:'CLEAR_ALL'});
 assert.equal(s.faults.length,0);
});
