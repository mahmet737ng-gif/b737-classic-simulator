'use strict';
// ISN-14 educational APU load coupling, not an aircraft-specific load schedule.
const assert=require('node:assert/strict');
const Load=require('../engine/integration/isn-apu-load-dynamics-v1');
const ECU=require('../engine/integration/isn-13-18-ecu-testbench-v1');
const Electrical=require('../engine/systems/electrical-v7');
const Loads=require('../engine/systems/electrical-loads-v8');
const TrainerCore=require('../engine/trainer/core');
const {WarningEngine}=require('../audio/warning-engine');
const Pneumatics=require('../engine/systems/pneumatics-v6');
const Pack=require('../engine/integration/isn-electrical-pack-v1');
const EngineAPU=require('../engine/integration/isn-engine-apu-v1');
const Start=require('../engine/integration/isn-start-sequence-v1');
const Chain=require('../engine/integration/isn-apu-start-chain-v1');
const ThrustPlanner=require('../engine/integration/isn-thrust-performance-v1');
const FuelRuntime=require('../engine/integration/isn-09-12-runtime-v1');
const sim=()=>new ECU.Testbench({Electrical,Loads,TrainerCore,WarningEngine,
 Pneumatics,Pack,EngineAPU,Start,Chain,ThrustPlanner,FuelRuntime});
assert.equal(Load.demand({selectedSources:{1:'GEN1'},switches:{AVIONICS:true}}).kva,0,
 'Consumer on an engine generator must not load the APU');
assert.equal(Load.demand({selectedSources:{1:'APU'},switches:{GALLEY:true}}).kva,0,
 'Consumer on non-APU side must not be transferred by guesswork');
assert.equal(Load.demand({selectedSources:{1:'APU'},switches:{AVIONICS:true}}).kva,8);
const test=sim();
assert.throws(()=>test.setElectricalConsumer('UNKNOWN',true),/Known training/);
test.battery(true);test.startAPU();test.advance(85000);
let idle=test.get();
assert.equal(idle.apu.phase,'READY');
assert.equal(idle.apu.egtC,390);
assert.equal(idle.apu.rpmPct,95.5);
assert.equal(idle.apu.load.loadDemandKva,0);
assert.equal(idle.apu.generator.voltageV,115);
test.setElectricalConsumer('AVIONICS',true);
test.advance(12000);
assert.equal(test.get().apu.load.loadDemandKva,0,'APU not connected: no electrical demand');
assert.equal(test.get().apu.egtC,390);
test.selectGenerator('APU',1);
test.advance(250);
let transient=test.get();
assert.equal(transient.apu.load.loadDemandKva,8);
assert.ok(transient.apu.rpmPct<95.5,'Transient load should create a small RPM droop');
assert.ok(transient.apu.rpmPct>=95,'Speed governor must not destabilize generator power');
test.advance(15000);
let one=test.get();
assert.ok(one.apu.egtC>idle.apu.egtC+8,'EGT rises with electrical load');
assert.ok(one.apu.fuelFlowEstimatedKgHr>110,'Fuel increases with electrical load');
assert.ok(one.apu.load.powerDemandPercent>20,'Shaft power demand increases');
assert.equal(one.apu.generator.voltageV,115);
assert.equal(one.apu.generator.frequencyHz,400);
assert.ok(Math.abs(one.apu.rpmPct-95.5)<.1,'Governor returns to regulated speed');
const baselineFuelBurn=one.fuel.burnedKg.apu;
test.setElectricalConsumer('CABIN_LIGHTS',true);
test.advance(15000);
const two=test.get();
assert.ok(two.apu.egtC>one.apu.egtC,'Additional electrical consumers raise EGT');
assert.ok(two.apu.load.actualLoadKva>one.apu.load.actualLoadKva);
assert.ok(two.apu.fuel.burnedKg.apu>baselineFuelBurn,'Additional simulated fuel consumed');
test.selectGenerator('APU',2);
test.setElectricalConsumer('GALLEY',true);
test.advance(16000);
const both=test.get();
assert.ok(both.apu.egtC>two.apu.egtC,'Second bus galley load raises EGT');
assert.ok(both.apu.load.loadDemandKva>=27);
assert.deepEqual(both.apu.load.connectedBuses,[1,2]);
test.apuBleed(true);
test.advance(16000);
const bleed=test.get();
assert.ok(bleed.apu.egtC>both.apu.egtC,'Pneumatic bleed imposes independent APU EGT rise');
test.setElectricalConsumer('GALLEY',false);
test.setElectricalConsumer('CABIN_LIGHTS',false);
test.setElectricalConsumer('AVIONICS',false);
test.apuBleed(false);
test.advance(35000);
const recovered=test.get();
assert.equal(recovered.apu.load.loadDemandKva,0);
assert.ok(recovered.apu.egtC<bleed.apu.egtC-25,'Removal of load cools APU');
assert.ok(recovered.apu.egtC<397,'Load-free EGT trends to initial governed target');
assert.ok(Math.abs(recovered.apu.rpmPct-95.5)<.1);
assert.equal(recovered.apu.generator.frequencyHz,400,'Regulated frequency remains 400Hz');
const fault=sim();fault.battery(true);fault.startAPU();fault.advance(85000);
fault.selectGenerator('APU',1);
fault.prepareFuel();fault.advance(20000);
const pump=fault.get();
assert.ok(pump.apu.load.consumers.some(c=>c.origin==='INSTRUCTOR_SURROGATE_BUS_NOT_WDM_VERIFIED'),
 'Selected training-mode electric fuel pumps automatically contribute APU load');
fault.setAPUFault('generatorFailure',true);fault.advance(18000);
assert.equal(fault.get().apu.generator.voltageV,0);
assert.equal(fault.get().apu.load.loadDemandKva,0);
console.log('PASS APU LOAD: source-gated bus consumers, pump surrogate loads, EGT/fuel/power response, regulated RPM droop recovery, bleed effect, automatic load shedding after GEN failure.');
