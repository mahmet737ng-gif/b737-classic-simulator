"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createEngine}=require("../fire-protection-lab/engine.js");
const {FireBellGate,fromATA26}=require("../audio/fire-bell-aural-gate-v1.js");
const source=path.join(__dirname,"../panel-mosaic-lab/cockpit/fire-bell-audio-unified-v1.js");
const hardware=path.join(__dirname,"../panel-mosaic-lab/cockpit/fire-hardware-unified.js");
const index=path.join(__dirname,"../panel-mosaic-lab/cockpit/index.html");
const power={batteryBus:true,hotBatteryBus:true,acTransfer1:true,onGround:true};
const fire=createEngine(power);
const gate=new FireBellGate();
let checks=0;
function check(condition,label){assert.ok(condition,label);checks++}
function live(){const evaluated=fire.evaluate();gate.setDemand("aircraft",fromATA26(evaluated));return evaluated}
function reset(){fire.dispatch({type:"RESET"});live()}
check(live().indications.FIRE_BELL===false,"No warning on initial state");
fire.dispatch({type:"SET_FIRE",unit:"ENG1",active:true});
check(live().indications.FIRE_BELL===true,"Engine 1 fire bell");
fire.dispatch({type:"SET_FIRE",unit:"ENG2",active:true});live();
check(gate.snapshot().sources.length===1,"Two simultaneous fires, one sound");
fire.dispatch({type:"SET_FIRE",unit:"APU",active:true});
check(live().indications.FIRE_BELL===true,"APU joined fire bell");
fire.dispatch({type:"BELL_CUTOUT"});
check(live().indications.FIRE_BELL===false,"Bell cutout silences even with fire still active");
fire.dispatch({type:"SET_FIRE",unit:"ENG1",active:false});
fire.dispatch({type:"SET_FIRE",unit:"ENG1",active:true});
check(live().indications.FIRE_BELL===true,"New fire occurrence resets acknowledgement");
reset();check(!gate.snapshot().active,"Reset silences bell");
fire.dispatch({type:"SET_FIRE",unit:"ENG2",active:true});
check(live().indications.FIRE_BELL===true,"Engine 2 alone");
reset();
fire.dispatch({type:"SET_FIRE",unit:"APU",active:true});
check(live().indications.FIRE_BELL===true,"APU alone");
reset();
fire.dispatch({type:"TEST",value:"OVHT_FIRE"});
check(live().indications.FIRE_BELL===true,"Momentary fire test sounds bell");
fire.dispatch({type:"TEST",value:null});
check(live().indications.FIRE_BELL===false,"Releasing fire test stops bell");
fire.dispatch({type:"TEST",value:"FAULT_INOP"});
check(live().indications.FIRE_BELL===false,"FAULT/INOP does not ring fire bell");
fire.dispatch({type:"EXT_TEST",value:"EXT_1"});
check(live().indications.FIRE_BELL===false,"EXT test does not ring fire bell");
reset();
fire.dispatch({type:"SET_OVERHEAT",unit:"ENG1",active:true});
check(live().indications.FIRE_BELL===false,"Overheat-only is not a fire bell");
reset();
fire.dispatch({type:"SET_FIRE",unit:"ENG1",active:true});
fire.dispatch({type:"SET_FIRE",unit:"ENG2",active:true});
check(live().indications.FIRE_BELL===true,"Both engines fire");
fire.dispatch({type:"SET_FIRE",unit:"ENG1",active:false});
check(live().indications.FIRE_BELL===true,"Second fire sustains bell");
gate.setDemand("lab",true);gate.setMuted("aircraft",true);
check(gate.snapshot().sources.join()==="lab","Isolated lab takes over audio");
gate.setDemand("lab",false);
check(!gate.snapshot().active,"Lab release stops shared voice while primary muted");
gate.setMuted("aircraft",false);
check(gate.snapshot().sources.join()==="aircraft","Return to aircraft audio");
check(!fromATA26({indications:{MASTER_FIRE_WARN:true}}),"No guess from red lamp only");
check(!fromATA26(null),"No audio on missing system sample");
const hardwareSource=fs.readFileSync(hardware,"utf8");
check(!/createOscillator|SpeechSynthesisUtterance/.test(hardwareSource),"Old generated fire bell removed");
check(hardwareSource.includes("soundLane=openLab?'aircraft':'lab'"),"Both hardware instances share driver");
const indexSource=fs.readFileSync(index,"utf8");
check(indexSource.indexOf("fire-bell-audio-unified-v1.js")<indexSource.indexOf("fire-hardware-unified.js"),
  "Real audio driver must load before fire hardware");
const driverSource=fs.readFileSync(source,"utf8");
check(driverSource.includes("bank.add('fireBell',file)"),"Owner sample persisted locally");
check(!/createOscillator|SpeechSynthesisUtterance/.test(driverSource),"No synthetic output");
check(driverSource.includes("gain.gain.linearRampToValueAtTime(0,when+duration)"),"Loop has seam fade");
check(driverSource.includes("gate.setMuted('aircraft',e.detail===true)"),"Lab isolation applied");
console.log(checks+" Fire Bell owner audio / ATA26 contract checks passed");
